CREATE OR REPLACE EDITIONABLE TRIGGER "LABPPTO"."DETALLEPARAMETROSID_SEQ_TR" 
 BEFORE INSERT ON LABPPTO.DETALLEPARAMETROS FOR EACH ROW
    WHEN (NEW.IdDetalle IS NULL) BEGIN
 SELECT LABPPTO.DETALLEPARAMETROSID_SEQ.NEXTVAL INTO :NEW.IdDetalle FROM DUAL;
END;

/
ALTER TRIGGER "LABPPTO"."DETALLEPARAMETROSID_SEQ_TR" ENABLE;
