CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABCONF"."ISNENTIDADES_TRG" 
BEFORE INSERT ON LABCONF.ISNENTIDADES
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID IS NULL THEN
      SELECT LABCONF.ISNENTIDADES_SEQ.NEXTVAL INTO :NEW.ID FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;


/
ALTER TRIGGER "LABCONF"."ISNENTIDADES_TRG" ENABLE;
