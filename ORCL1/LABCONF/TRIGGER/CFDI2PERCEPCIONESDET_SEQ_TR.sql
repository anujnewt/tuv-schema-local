CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABCONF"."CFDI2PERCEPCIONESDET_SEQ_TR" 
 BEFORE INSERT ON LABCONF.cfdi2PercepcionesDetalle FOR EACH ROW
     WHEN (NEW.idPercepcion IS NULL) BEGIN
 SELECT LABCONF.cfdi2PercepcionesDetalle_seq.NEXTVAL INTO :NEW.idPercepcion FROM DUAL;
END;


/
ALTER TRIGGER "LABCONF"."CFDI2PERCEPCIONESDET_SEQ_TR" ENABLE;
