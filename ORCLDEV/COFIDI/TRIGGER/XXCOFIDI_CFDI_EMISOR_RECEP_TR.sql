CREATE OR REPLACE NONEDITIONABLE TRIGGER "COFIDI"."XXCOFIDI_CFDI_EMISOR_RECEP_TR" 
BEFORE INSERT ON "COFIDI".XXCOFIDI_CFDI_EMISOR_RECEP_TAB
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_CFDI_EMISOR_RECEP_PK IS NULL THEN
      SELECT "COFIDI".XXCOFIDI_CFDI_EMISOR_RECEP_SQ.NEXTVAL
          INTO :NEW.ID_CFDI_EMISOR_RECEP_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;

/
ALTER TRIGGER "COFIDI"."XXCOFIDI_CFDI_EMISOR_RECEP_TR" ENABLE;
