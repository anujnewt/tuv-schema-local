CREATE OR REPLACE NONEDITIONABLE TRIGGER "COFIDI"."XXCOFIDI_EMP_ORI_SER_TR" 
BEFORE INSERT ON COFIDI.XXCOFIDI_EMP_ORI_SER_TAB
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_EMP_ORI_SER_PK IS NULL THEN
      SELECT COFIDI.XXCOFIDI_EMP_ORI_SER_SQ.NEXTVAL
          INTO :NEW.ID_EMP_ORI_SER_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;

/;
ALTER TRIGGER "COFIDI"."XXCOFIDI_EMP_ORI_SER_TR" ENABLE;

/
