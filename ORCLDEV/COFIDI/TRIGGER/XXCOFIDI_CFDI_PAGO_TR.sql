CREATE OR REPLACE NONEDITIONABLE TRIGGER "COFIDI"."XXCOFIDI_CFDI_PAGO_TR" 
BEFORE INSERT ON "COFIDI".XXCOFIDI_CFDI_PAGO_TAB
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_CFDI_PAGO_PK IS NULL THEN
      SELECT "COFIDI".XXCOFIDI_CFDI_PAGO_SQ.NEXTVAL
          INTO :NEW.ID_CFDI_PAGO_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;

/
ALTER TRIGGER "COFIDI"."XXCOFIDI_CFDI_PAGO_TR" ENABLE;
