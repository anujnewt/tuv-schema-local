CREATE OR REPLACE NONEDITIONABLE TRIGGER "COFIDI"."XXCOFIDI_USUARIO_LDAP_TR" 
BEFORE INSERT ON "COFIDI".XXCOFIDI_USUARIO_LDAP_TAB
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_USUARIO_LDAP_PK IS NULL THEN
      SELECT "COFIDI".XXCOFIDI_USUARIO_LDAP_SQ.NEXTVAL
      INTO :NEW.ID_USUARIO_LDAP_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;

/
ALTER TRIGGER "COFIDI"."XXCOFIDI_USUARIO_LDAP_TR" ENABLE;
