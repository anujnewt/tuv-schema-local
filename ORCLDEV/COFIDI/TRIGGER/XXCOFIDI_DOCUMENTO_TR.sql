CREATE OR REPLACE NONEDITIONABLE TRIGGER "COFIDI"."XXCOFIDI_DOCUMENTO_TR" 
BEFORE INSERT ON "COFIDI".XXCOFIDI_DOCUMENTO_TAB
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_DOCUMENTO_PK IS NULL THEN
      SELECT "COFIDI".XXCOFIDI_DOCUMENTO_SQ.NEXTVAL
          INTO :NEW.ID_DOCUMENTO_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;

/
ALTER TRIGGER "COFIDI"."XXCOFIDI_DOCUMENTO_TR" ENABLE;
