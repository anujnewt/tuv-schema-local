CREATE OR REPLACE NONEDITIONABLE TRIGGER "COFIDI"."XXCOFIDI_BITACORA_TR" 
BEFORE INSERT ON "COFIDI".XXCOFIDI_BITACORA_TAB
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_BITACORA_PK IS NULL THEN
      SELECT "COFIDI".XXCOFIDI_BITACORA_SQ.NEXTVAL
          INTO :NEW.ID_BITACORA_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;

/
ALTER TRIGGER "COFIDI"."XXCOFIDI_BITACORA_TR" ENABLE;
