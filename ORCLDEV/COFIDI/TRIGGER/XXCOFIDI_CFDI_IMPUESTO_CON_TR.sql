CREATE OR REPLACE NONEDITIONABLE TRIGGER "COFIDI"."XXCOFIDI_CFDI_IMPUESTO_CON_TR" 
BEFORE INSERT ON "COFIDI".XXCOFIDI_CFDI_IMPUESTO_CON_TAB
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_CFDI_IMPUESTO_CONCEPTO_PK IS NULL THEN
      SELECT "COFIDI".XXCOFIDI_CFDI_IMPUESTO_CON_SQ.NEXTVAL
          INTO :NEW.ID_CFDI_IMPUESTO_CONCEPTO_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;

/
ALTER TRIGGER "COFIDI"."XXCOFIDI_CFDI_IMPUESTO_CON_TR" ENABLE;
