CREATE OR REPLACE NONEDITIONABLE TRIGGER "COFIDI"."XXCOFIDI_PARAMETRO_TR" 
BEFORE INSERT ON "COFIDI".XXCOFIDI_PARAMETRO_CT_TAB
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_PARAMETRO_PK IS NULL THEN
      SELECT "COFIDI".XXCOFIDI_PARAMETRO_SQ.NEXTVAL
          INTO :NEW.ID_PARAMETRO_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;

/
ALTER TRIGGER "COFIDI"."XXCOFIDI_PARAMETRO_TR" ENABLE;
