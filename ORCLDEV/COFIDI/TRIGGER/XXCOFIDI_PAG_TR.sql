CREATE OR REPLACE NONEDITIONABLE TRIGGER "COFIDI"."XXCOFIDI_PAG_TR" 
BEFORE INSERT ON "COFIDI".XXCOFIDI_PAGINACION_CT_TAB
FOR EACH ROW
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_PAGINACION_PK IS NULL THEN
      SELECT "COFIDI".XXCOFIDI_PAG_SQ.NEXTVAL
          INTO :NEW.ID_PAGINACION_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;

/
ALTER TRIGGER "COFIDI"."XXCOFIDI_PAG_TR" ENABLE;
