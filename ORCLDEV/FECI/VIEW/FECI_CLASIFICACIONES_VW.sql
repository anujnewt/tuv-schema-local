CREATE OR REPLACE FORCE EDITIONABLE VIEW "FECI"."FECI_CLASIFICACIONES_VW" ("FOLIO_RECIBO", "TIPO_RECIBO", "FEC_OPERATIVA", "IMPORTE", "COD_MONEDA", "DES_MONEDA", "COD_EMPRESA", "DES_EMPRESA", "COD_CLIENTE", "REF_CLIENTE", "NOM_CLIENTE", "CLASE_CLIENTE", "METODO_PAGO", "NOM_BANCO_EMISOR", "NUM_CHEQUERA", "NUM_CHEQUE", "NUM_OPERACION", "TIPO_CAMBIO_ORIGEN", "TIPO_CAMBIO_DOLAR", "FEC_CLASIFICACION", "FEC_APLICACION", "COD_ESTADO_RECIBO", "FEC_DEPOSITO", "ID_CLASIFICACION", "ORDEN", "PORCENTAJE_IVA", "IMPORTE_ORG", "MONTO_BASE_ORG", "MONTO_IVA_ORG", "IMPORTE_MXN", "MONTO_BASE_MXN", "MONTO_IVA_MXN", "IMPORTE_USD", "MONTO_BASE_USD", "MONTO_IVA_USD", "COD_SEGMENTO", "DES_SEGMENTO", "COD_MONEDA_SEGMENTO", "COD_GRUPO_FORECAST", "DES_GRUPO_FORECAST", "COD_CONCEPTO", "DES_CONCEPTO", "COD_REGION", "DES_REGION", "COD_PAIS", "DES_PAIS", "DESC_CPS") AS 
  SELECT  REC.FOLIO_RECIBO
            ,REC.TIPO_RECIBO
            ,REC.FEC_OPERATIVA
            ,REC.IMPORTE
            ,REC.COD_MONEDA
            ,REC.DES_MONEDA
            ,REC.COD_EMPRESA
            ,REC.DES_EMPRESA
            ,REC.COD_CLIENTE
            ,REC.REF_CLIENTE
            ,REC.NOM_CLIENTE
            ,REC.CLASE_CLIENTE
            ,REC.METODO_PAGO
            ,REC.NOM_BANCO_EMISOR
            ,REC.NUM_CHEQUERA
            ,REC.NUM_CHEQUE
            ,REC.NUM_OPERACION
            ,REC.TIPO_CAMBIO_ORIGEN
            ,REC.TIPO_CAMBIO_DOLAR
            ,REC.FEC_CLASIFICACION
            ,REC.FEC_APLICACION
            ,REC.COD_ESTADO_RECIBO
            ,REC.FEC_DEPOSITO
            ,CLS.ID_CLASIFICACION
            ,CLS.ORDEN
            ,CLS.PORCENTAJE_IVA
            ,CLS.IMPORTE_ORG
            ,CLS.MONTO_BASE_ORG
            ,CLS.MONTO_IVA_ORG
            ,CLS.IMPORTE_MXN
            ,CLS.MONTO_BASE_MXN
            ,CLS.MONTO_IVA_MXN
            ,CLS.IMPORTE_USD
            ,CLS.MONTO_BASE_USD
            ,CLS.MONTO_IVA_USD
            ,CLS.COD_SEGMENTO
            ,SEG.DES_SEGMENTO
            ,SEG.COD_MONEDA AS COD_MONEDA_SEGMENTO
            ,CLS.COD_GRUPO_FORECAST
            ,GFC.DES_GRUPO_FORECAST
            ,CLS.COD_CONCEPTO
            ,CON.DES_CONCEPTO
            ,CLS.COD_REGION
            ,REG.DES_REGION
            ,CLS.COD_PAIS
            ,PAI.DES_PAIS
            ,CLS.DESC_CPS
    FROM FECI_CLASIFICACION_TAB CLS
    INNER JOIN FECI_RECIBOS_VW REC ON CLS.FOLIO_RECIBO = REC.FOLIO_RECIBO AND CLS.TIPO_RECIBO=REC.TIPO_RECIBO
    INNER JOIN FECI_GRUPO_FORECAST_CAT GFC ON CLS.COD_GRUPO_FORECAST = GFC.COD_GRUPO_FORECAST
    INNER JOIN FECI_SEGMENTO_CAT SEG ON CLS.COD_SEGMENTO = SEG.COD_SEGMENTO
    INNER JOIN FECI_CONCEPTO_CAT CON ON CLS.COD_CONCEPTO = CON.COD_CONCEPTO
    LEFT OUTER JOIN FECI_REGION_CAT REG ON CLS.COD_REGION = REG.COD_REGION
    LEFT OUTER JOIN FECI_PAIS_CAT PAI ON CLS.COD_PAIS = PAI.COD_PAIS
    WHERE REC.IND_ESTADO = 1 AND CLS.IND_ESTADO = 1 AND REC.COD_ESTADO_RECIBO = 'APLC' AND GFC.IND_ESTADO = 1;
