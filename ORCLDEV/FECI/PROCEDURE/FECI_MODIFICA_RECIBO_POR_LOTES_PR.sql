CREATE OR REPLACE EDITIONABLE PROCEDURE "FECI"."FECI_MODIFICA_RECIBO_POR_LOTES_PR" 
AS
-- PGV moved types end

-- PGV moved types end
feci_cursor             SYS_REFCURSOR;
SELECT_FEC_ORI          DATE;
SELECT_FEC_ORI_OPC      DATE;
SELECT_FEC_DOL          DATE;
SELECT_FEC_DOL_OPC      DATE;
SELECT_VAL_ORI          NUMBER;
SELECT_VAL_ORI_OPC      NUMBER;
SELECT_VAL_DOL          NUMBER;
SELECT_VAL_DOL_OPC      NUMBER;
BEGIN
    DECLARE
-- PGV moved types start

-- PGV moved types start
 CURSOR recibo IS
    SELECT *
    FROM FECI_RECIBO_TAB
    WHERE FEC_TC_ORIGEN IS NULL AND TIPO_CAMBIO_DOLAR IS NULL;
    BEGIN
        for r in recibo loop
        dbms_output.put_line(r.FEC_TC_ORIGEN||' '||r.TIPO_CAMBIO_DOLAR);
        SELECT TC.FEC_FECHA_TC, TC.NUM_VALOR INTO SELECT_FEC_ORI_OPC, SELECT_VAL_ORI_OPC
        FROM FECI_TIPO_CAMBIO_CAT TC
        WHERE TC.FEC_FECHA_TC = (SELECT MAX(FEC_FECHA_TC) FROM FECI_TIPO_CAMBIO_CAT)
        AND TC.COD_MONEDA = r.COD_MONEDA;
        SELECT_FEC_ORI := SELECT_FEC_ORI_OPC;
        SELECT_VAL_ORI := SELECT_VAL_ORI_OPC;
        UPDATE FECI_RECIBO_TAB
        SET FEC_TC_ORIGEN = SELECT_FEC_ORI,
        TIPO_CAMBIO_ORIGEN = SELECT_VAL_ORI,
        FEC_ULT_MODIFICACION = SYSDATE
        WHERE FEC_TC_ORIGEN IS NULL AND TIPO_CAMBIO_ORIGEN IS NULL;
    end loop;
    END;
    SELECT TC.FEC_FECHA_TC, TC.NUM_VALOR INTO SELECT_FEC_DOL_OPC, SELECT_VAL_DOL_OPC
    FROM FECI_TIPO_CAMBIO_CAT TC
    WHERE TC.FEC_FECHA_TC = (SELECT MAX(FEC_FECHA_TC) FROM FECI_TIPO_CAMBIO_CAT)
    AND TC.COD_MONEDA = 'USD';
    SELECT_FEC_DOL := SELECT_FEC_DOL_OPC;
    SELECT_VAL_DOL := SELECT_VAL_DOL_OPC;
    UPDATE FECI_RECIBO_TAB
    SET FEC_TC_DOLAR = SELECT_FEC_DOL,
    TIPO_CAMBIO_DOLAR = SELECT_VAL_DOL,
    FEC_ULT_MODIFICACION = SYSDATE
    WHERE FEC_TC_DOLAR IS NULL AND TIPO_CAMBIO_DOLAR IS NULL;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('SELECT_FEC_OPC ');
END FECI_MODIFICA_RECIBO_POR_LOTES_PR;
/
