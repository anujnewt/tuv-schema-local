CREATE OR REPLACE EDITIONABLE PROCEDURE "FECI"."FECI_OBTENER_REPORTE_COBRANZA_FORECAST" (
    p_ano1 IN NUMBER,
    p_mes IN NUMBER,
    p_MONEDA_COLUMN_NAME VARCHAR2,
    p_MONEDA_COLUMN_NAME_C VARCHAR2
)
IS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
    v_sql_query VARCHAR2(4000);
     feci_cursor SYS_REFCURSOR;
BEGIN
    -- Construir la consulta din?ca
    v_sql_query :=
        'WITH Estimacion AS (' ||
        '    SELECT ' ||
        '       COD_GRUPO_FORECAST,' ||
        '        COD_SEGMENTO,' ||
        '        SUM(CASE WHEN NUM_SEMANA = 1 THEN ' || p_MONEDA_COLUMN_NAME || ' ELSE 0 END) AS ESTIMACION_SEM1,' ||
        '        SUM(CASE WHEN NUM_SEMANA = 2 THEN ' || p_MONEDA_COLUMN_NAME || ' ELSE 0 END) AS ESTIMACION_SEM2,' ||
        '        SUM(CASE WHEN NUM_SEMANA = 3 THEN ' || p_MONEDA_COLUMN_NAME || ' ELSE 0 END) AS ESTIMACION_SEM3,' ||
        '        SUM(CASE WHEN NUM_SEMANA = 4 THEN ' || p_MONEDA_COLUMN_NAME || ' ELSE 0 END) AS ESTIMACION_SEM4,' ||
        '        SUM(CASE WHEN NUM_SEMANA = 5 THEN ' || p_MONEDA_COLUMN_NAME || ' ELSE 0 END) AS ESTIMACION_SEM5 ' ||
        '    FROM FECI_ESTIMACION_TAB ' ||
        '    WHERE NUM_ANIO = '|| p_ano1 ||' AND NUM_MES = ' || p_mes ||
        '    GROUP BY COD_GRUPO_FORECAST, COD_SEGMENTO ' ||
        '),' ||
        'Cobranza AS (' ||
        '   SELECT ' ||
        '    c.COD_GRUPO_FORECAST,' ||
        '    c.COD_SEGMENTO, '  ||
        '    c.DES_GRUPO_FORECAST, ' ||
        '    c.DES_SEGMENTO, ' ||
        '    SUM(CASE WHEN c.FEC_OPERATIVA BETWEEN w1.FEC_INICIO_SEMANA_1 AND w1.FEC_FIN_SEMANA_1 AND w1.NUM_ANIO = '|| p_ano1 ||' AND w1.NUM_MES =  ' || p_mes ||' THEN c.' || p_MONEDA_COLUMN_NAME_C || ' ELSE 0 END) AS COBRANZA_SEM1,' ||
        '    SUM(CASE WHEN c.FEC_OPERATIVA BETWEEN w2.FEC_INICIO_SEMANA_2 AND w2.FEC_FIN_SEMANA_2 AND w2.NUM_ANIO = '|| p_ano1 ||' AND w2.NUM_MES =  ' || p_mes ||' THEN c.' || p_MONEDA_COLUMN_NAME_C || ' ELSE 0 END) AS COBRANZA_SEM2,' ||
        '    SUM(CASE WHEN c.FEC_OPERATIVA BETWEEN w3.FEC_INICIO_SEMANA_3 AND w3.FEC_FIN_SEMANA_3 AND w3.NUM_ANIO = '|| p_ano1 ||' AND w3.NUM_MES =  ' || p_mes ||' THEN c.' || p_MONEDA_COLUMN_NAME_C || ' ELSE 0 END) AS COBRANZA_SEM3,' ||
        '    SUM(CASE WHEN c.FEC_OPERATIVA BETWEEN w4.FEC_INICIO_SEMANA_4 AND w4.FEC_FIN_SEMANA_4 AND w4.NUM_ANIO = '|| p_ano1 ||' AND w4.NUM_MES =  ' || p_mes ||' THEN c.' || p_MONEDA_COLUMN_NAME_C || ' ELSE 0 END) AS COBRANZA_SEM4,' ||
        '    SUM(CASE WHEN c.FEC_OPERATIVA BETWEEN w5.FEC_INICIO_SEMANA_5 AND w5.FEC_FIN_SEMANA_5 AND w5.NUM_ANIO = '|| p_ano1 ||' AND w5.NUM_MES =  ' || p_mes ||' THEN c.' || p_MONEDA_COLUMN_NAME_C || ' ELSE 0 END) AS COBRANZA_SEM5' ||
        '        FROM FECI_CLASIFICACIONES_REP_VW c' ||
        '        LEFT JOIN' ||
        '            FECI_SEMANAS_ESTIMACION_TAB w1 ON c.FEC_OPERATIVA BETWEEN w1.FEC_INICIO_SEMANA_1 AND w1.FEC_FIN_SEMANA_1' ||
        '        LEFT JOIN' ||
        '            FECI_SEMANAS_ESTIMACION_TAB w2 ON c.FEC_OPERATIVA BETWEEN w2.FEC_INICIO_SEMANA_2 AND w2.FEC_FIN_SEMANA_2' ||
        '        LEFT JOIN' ||
        '            FECI_SEMANAS_ESTIMACION_TAB w3 ON c.FEC_OPERATIVA BETWEEN w3.FEC_INICIO_SEMANA_3 AND w3.FEC_FIN_SEMANA_3' ||
        '        LEFT JOIN' ||
        '            FECI_SEMANAS_ESTIMACION_TAB w4 ON c.FEC_OPERATIVA BETWEEN w4.FEC_INICIO_SEMANA_4 AND w4.FEC_FIN_SEMANA_4' ||
        '        LEFT JOIN' ||
        '            FECI_SEMANAS_ESTIMACION_TAB w5 ON c.FEC_OPERATIVA BETWEEN w5.FEC_INICIO_SEMANA_5 AND w5.FEC_FIN_SEMANA_5' ||
        '        GROUP BY c.COD_GRUPO_FORECAST, c.COD_SEGMENTO,c.DES_GRUPO_FORECAST, c.DES_SEGMENTO' ||
        ')
        SELECT
            c.COD_GRUPO_FORECAST,
            c.COD_SEGMENTO,
            c.DES_GRUPO_FORECAST,
            c.DES_SEGMENTO,
            e.ESTIMACION_SEM1,
            c.COBRANZA_SEM1,
            c.COBRANZA_SEM1 - e.ESTIMACION_SEM1 AS VARIACION_SEM1,
            e.ESTIMACION_SEM2,
            c.COBRANZA_SEM2,
            c.COBRANZA_SEM2 - e.ESTIMACION_SEM2 AS VARIACION_SEM2,
            e.ESTIMACION_SEM3,
            c.COBRANZA_SEM3,
            c.COBRANZA_SEM3 - e.ESTIMACION_SEM3 AS VARIACION_SEM3,
            e.ESTIMACION_SEM4,
            c.COBRANZA_SEM4,
            c.COBRANZA_SEM4 - e.ESTIMACION_SEM4 AS VARIACION_SEM4,
            e.ESTIMACION_SEM5,
            c.COBRANZA_SEM5,
            c.COBRANZA_SEM5 - e.ESTIMACION_SEM5 AS VARIACION_SEM5,
            e.ESTIMACION_SEM1 + e.ESTIMACION_SEM2 + e.ESTIMACION_SEM3 + e.ESTIMACION_SEM4 + e.ESTIMACION_SEM5 AS ESTIMACION_TOTAL,
            c.COBRANZA_SEM1 + c.COBRANZA_SEM2 + c.COBRANZA_SEM3 + c.COBRANZA_SEM4 + c.COBRANZA_SEM5 AS COBRANZA_TOTAL,
            (c.COBRANZA_SEM1 + c.COBRANZA_SEM2 + c.COBRANZA_SEM3 + c.COBRANZA_SEM4 + c.COBRANZA_SEM5) - (e.ESTIMACION_SEM1 + e.ESTIMACION_SEM2 + e.ESTIMACION_SEM3 + e.ESTIMACION_SEM4 + e.ESTIMACION_SEM5) AS VARIACION_TOTAL
        FROM Estimacion e
        FULL OUTER JOIN Cobranza c ON e.COD_GRUPO_FORECAST = c.COD_GRUPO_FORECAST AND e.COD_SEGMENTO = c.COD_SEGMENTO';
    -- Ejecutar la consulta din?ca
    OPEN feci_cursor FOR v_sql_query;
    DBMS_SQL.RETURN_RESULT(feci_cursor);
     DBMS_OUTPUT.PUT_LINE('Consulta din?ca: ' || v_sql_query);
END FECI_OBTENER_REPORTE_COBRANZA_FORECAST;
