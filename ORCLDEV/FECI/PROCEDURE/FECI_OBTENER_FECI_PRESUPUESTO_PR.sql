CREATE OR REPLACE EDITIONABLE PROCEDURE "FECI"."FECI_OBTENER_FECI_PRESUPUESTO_PR" 
(
    p_ANIO         NUMBER,
    p_MES         NUMBER,
    p_MONEDA         VARCHAR2
)
AS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
feci_cursors SYS_REFCURSOR;
BEGIN
   open feci_cursors for
        SELECT
    ID_PRESUPUESTO,
    COD_SEGMENTO,
    COD_CONCEPTO,
    COD_MONEDA,
    COD_REGION,
    FEC_PRESUPUESTO,
    NUM_GESTION,
    NUM_IMPORTE
FROM
    FECI_PRESUPUESTO_TAB
WHERE
    EXTRACT(YEAR FROM FEC_PRESUPUESTO) = TO_NUMBER(p_ANIO)
    AND EXTRACT(MONTH FROM FEC_PRESUPUESTO) = TO_NUMBER(p_MES)
    AND COD_MONEDA = p_MONEDA;
    DBMS_SQL.RETURN_RESULT(feci_cursors);
END FECI_OBTENER_FECI_PRESUPUESTO_PR ;
/
