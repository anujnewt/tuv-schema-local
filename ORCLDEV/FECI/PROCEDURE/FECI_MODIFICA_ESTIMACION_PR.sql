BEGIN
      UPDATE FECI_ESTIMACION_TAB
      SET NUM_IMPORTE_MXN = p_IMPORTE_MXN,
      NUM_IMPORTE_USD = p_IMPORTE_USD,
      FEC_ULT_MODIFICACION = SYSDATE,
      ID_USUARIO_ULT_MODIF = p_ID_USUARIO
