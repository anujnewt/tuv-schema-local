CREATE OR REPLACE EDITIONABLE PROCEDURE "FECI"."FECI_MODIFICA_ESTIMACION_PR" 
(
        p_ID                NUMBER,
        p_ID_USUARIO         NUMBER,
        p_IMPORTE_MXN         NUMBER,
        p_IMPORTE_USD        NUMBER
)
IS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
