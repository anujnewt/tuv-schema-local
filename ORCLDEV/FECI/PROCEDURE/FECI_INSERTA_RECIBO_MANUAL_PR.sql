CREATE OR REPLACE EDITIONABLE PROCEDURE "FECI"."FECI_INSERTA_RECIBO_MANUAL_PR" 
(
        p_FECHA         DATE,
        p_MONEDA         VARCHAR2,
        p_EMPRESA         VARCHAR2,
        p_REF_CLIENTE       VARCHAR2,
        p_NOM_CLIENTE       VARCHAR2,
        p_CLASE_CLIENTE       VARCHAR2,
        p_METODO_PAGO       VARCHAR2,
        p_BANCO_EMISOR       VARCHAR2,
        p_NUM_CHEQUERA       VARCHAR2,
        p_NUM_CHEQUE       VARCHAR2,
        p_NUM_OPERACION       VARCHAR2,
        p_Usuario              NUMBER,
        p_COD_CLIENTE       VARCHAR2,
        p_IMPORTE           NUMBER
)
AS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
    ID_REGISTRO NUMBER;
    feci_cursors SYS_REFCURSOR;
BEGIN
     INSERT INTO FECI_RECIBO_MANUAL_TAB
        (
            FEC_CONTABILIDAD ,FEC_OPERATIVA,IMPORTE,COD_MONEDA,COD_EMPRESA,REF_CLIENTE,NOM_CLIENTE,CLASE_CLIENTE,
            METODO_PAGO,NOM_BANCO_EMISOR,NUM_CHEQUERA,NUM_CHEQUE,NUM_OPERACION,TIPO_CAMBIO_ORIGEN,FEC_TC_ORIGEN,
            TIPO_CAMBIO_DOLAR,FEC_TC_DOLAR,ID_USUARIO_CLASIFICACION,FEC_CLASIFICACION,ID_USUARIO_APLICACION,
            FEC_APLICACION,COD_ESTADO_RECIBO,FEC_CREACION,FEC_ULT_MODIFICACION,ID_USUARIO_CREACION,
            ID_USUARIO_ULT_MODIF,IND_ESTADO,COD_CLIENTE)
             VALUES(
             TO_DATE(TO_CHAR(p_FECHA, 'yyyy-MM-dd'), 'yyyy-MM-dd') ,TO_DATE(TO_CHAR(p_FECHA, 'yyyy-MM-dd'), 'yyyy-MM-dd'),p_IMPORTE,p_MONEDA,p_EMPRESA,p_REF_CLIENTE,p_NOM_CLIENTE,p_CLASE_CLIENTE,
             p_METODO_PAGO,p_BANCO_EMISOR,p_NUM_CHEQUERA,p_NUM_CHEQUE,p_NUM_OPERACION,NULL,NULL,
             NULL,NULL,NULL,NULL,NULL,NULL,'PEND',SYSDATE,SYSDATE,p_USUARIO,0,1,p_COD_CLIENTE
             )
             returning FOLIO_RECIBO_MANUAL INTO ID_REGISTRO;
            FECI_MODIFICA_TIPO_CAMBIO_RECIBO_PR(ID_REGISTRO, 'MANUAL', p_Usuario);
            open feci_cursors for
               SELECT FOLIO_RECIBO_MANUAL FROM FECI_RECIBO_MANUAL_TAB WHERE FOLIO_RECIBO_MANUAL =  ID_REGISTRO;
    DBMS_SQL.RETURN_RESULT(feci_cursors);
END FECI_INSERTA_RECIBO_MANUAL_PR ;
/
