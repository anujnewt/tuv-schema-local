CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABPROD"."CFDI2PERCEPCIONESDET_SEQ_TR" 
 BEFORE INSERT ON LABPROD.cfdi2PercepcionesDetalle FOR EACH ROW
     WHEN (NEW.idPercepcion IS NULL) BEGIN
 SELECT LABPROD.cfdi2PercepcionesDetalle_seq.NEXTVAL INTO :NEW.idPercepcion FROM DUAL;
END;


/
ALTER TRIGGER "LABPROD"."CFDI2PERCEPCIONESDET_SEQ_TR" ENABLE;
