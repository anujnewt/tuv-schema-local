CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABPROD"."RECIBOS_INTERFACE_SEQ_TR" 
 BEFORE INSERT ON LABPROD.RECIBOS_INTERFACE FOR EACH ROW
   WHEN (
NEW.ID IS NULL
      ) BEGIN
 SELECT LABPROD.RECIBOS_INTERFACE_seq.NEXTVAL INTO :NEW.ID FROM DUAL;
END;



/
ALTER TRIGGER "LABPROD"."RECIBOS_INTERFACE_SEQ_TR" ENABLE;
