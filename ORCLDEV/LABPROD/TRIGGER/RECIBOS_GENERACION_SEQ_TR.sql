CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABPROD"."RECIBOS_GENERACION_SEQ_TR" 
 BEFORE INSERT ON LABPROD.RECIBOS_GENERACION FOR EACH ROW
   WHEN (
NEW.ID IS NULL
      ) BEGIN
 SELECT LABPROD.RECIBOS_GENERACION_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL;
END;


/
ALTER TRIGGER "LABPROD"."RECIBOS_GENERACION_SEQ_TR" ENABLE;
