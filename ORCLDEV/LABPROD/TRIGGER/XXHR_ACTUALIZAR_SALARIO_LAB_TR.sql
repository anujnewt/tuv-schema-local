CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABPROD"."XXHR_ACTUALIZAR_SALARIO_LAB_TR" 
      BEFORE INSERT ON LABPROD.XXHR_ACTUALIZAR_SALARIO_LAB
      FOR EACH ROW
    BEGIN
      IF :new.ID_LABORA IS NULL THEN
        SELECT "LABPROD".XXHR_ACTUALIZAR_SALARIO_LAB_SE.nextval INTO :new.ID_LABORA FROM dual;
      END IF;
    END;


/
ALTER TRIGGER "LABPROD"."XXHR_ACTUALIZAR_SALARIO_LAB_TR" ENABLE;
