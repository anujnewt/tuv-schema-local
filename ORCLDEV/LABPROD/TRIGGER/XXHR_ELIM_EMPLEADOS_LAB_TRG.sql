CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABPROD"."XXHR_ELIM_EMPLEADOS_LAB_TRG" 
      BEFORE INSERT ON LABPROD.XXHR_ELIM_EMPLEADOS_LAB
      FOR EACH ROW
    BEGIN
      IF :new.ID_LABORA IS NULL THEN
        SELECT "LABPROD".XXHR_ELIM_EMPLEADOS_LAB_seq.nextval INTO :new.ID_LABORA FROM dual;
      END IF;
    END;


/
ALTER TRIGGER "LABPROD"."XXHR_ELIM_EMPLEADOS_LAB_TRG" ENABLE;
