CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABPROD"."ISNENTIDADES_TRG" 
BEFORE INSERT ON LABPROD.ISNENTIDADES 
FOR EACH ROW 
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID IS NULL THEN
      SELECT LABPROD.ISNENTIDADES_SEQ.NEXTVAL INTO :NEW.ID FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;


/
ALTER TRIGGER "LABPROD"."ISNENTIDADES_TRG" ENABLE;
