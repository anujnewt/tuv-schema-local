CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABPROD"."NMCOFALT_TRG" 
  AFTER INSERT ON LABPROD.NMCOFALT
  FOR EACH ROW
BEGIN
      IF :NEW.FAL_TIPIMS <> 'F' THEN
        LABPROD.SP_NMREGINC (:NEW.FAL_KEYEMP,
                        :NEW.FAL_TIPIMS,
                        :NEW.FAL_DIAINC,
                        :NEW.FAL_FECINI);
      END IF;
  END;


/
ALTER TRIGGER "LABPROD"."NMCOFALT_TRG" ENABLE;
