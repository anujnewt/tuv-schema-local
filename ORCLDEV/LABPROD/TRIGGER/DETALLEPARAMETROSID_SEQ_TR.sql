CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABPROD"."DETALLEPARAMETROSID_SEQ_TR" 
 BEFORE INSERT ON LABPROD.DETALLEPARAMETROS FOR EACH ROW
    WHEN (NEW.IdDetalle IS NULL) BEGIN
 SELECT LABPROD.DETALLEPARAMETROSID_SEQ.NEXTVAL INTO :NEW.IdDetalle FROM DUAL;
END;

/
ALTER TRIGGER "LABPROD"."DETALLEPARAMETROSID_SEQ_TR" ENABLE;
