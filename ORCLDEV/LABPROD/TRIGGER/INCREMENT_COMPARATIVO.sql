CREATE OR REPLACE NONEDITIONABLE TRIGGER "LABPROD"."INCREMENT_COMPARATIVO" 
   BEFORE INSERT
     ON LABPROD.comparativo
     REFERENCING NEW AS NEW
     FOR EACH ROW
   BEGIN
     SELECT seq_comparativo.nextval INTO :NEW.ID_comp FROM dual;
   END;


/
ALTER TRIGGER "LABPROD"."INCREMENT_COMPARATIVO" ENABLE;
