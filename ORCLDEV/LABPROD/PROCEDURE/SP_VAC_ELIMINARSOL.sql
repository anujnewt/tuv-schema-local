CREATE OR REPLACE NONEDITIONABLE PROCEDURE "LABPROD"."SP_VAC_ELIMINARSOL" 
(
  KEYSOL IN NUMBER,
  KEYCON IN VARCHAR2,
  RESULTADO OUT NUMBER
) AS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
NUMDIA DECIMAL(10,2);
NUMANI NUMBER(10,0);
KEYEMP NUMBER(10,0);
FECPER DATE;
BEGIN
  BEGIN
    SELECT SOL_NUMDIA,SOL_NUMANI,SOL_FECPER,SOL_KEYEMP INTO NUMDIA,NUMANI,FECPER,KEYEMP
    FROM LABPROD.MOLOSOLI
    WHERE SOL_KEYSOL = KEYSOL;
  EXCEPTION
     WHEN NO_DATA_FOUND THEN
       RESULTADO := 0;
       RETURN;
  END;
  BEGIN
    DELETE FROM LABPROD.MOLOTRPR WHERE TRP_KEYCON = 'VA' AND TRP_CA2AUX = KEYSOL AND TRP_KEYEMP = KEYEMP;
    DELETE FROM LABPROD.MOLOSOLI WHERE SOL_KEYSOL = KEYSOL;
    UPDATE LABPROD.MOLODIAD SET DIA_DIASAL = DIA_DIASAL + NUMDIA
    WHERE DIA_KEYEMP = KEYEMP
    AND DIA_KEYCON = 'VA'
    AND DIA_NUMANI = NUMANI
    AND DIA_FECINI = FECPER;
    COMMIT;
    RESULTADO := 0;
  EXCEPTION
    WHEN OTHERS THEN
      RESULTADO := 1;
      RETURN;
  END;
END SP_VAC_ELIMINARSOL;
/
