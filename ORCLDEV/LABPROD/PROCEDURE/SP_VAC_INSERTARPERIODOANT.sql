CREATE OR REPLACE NONEDITIONABLE PROCEDURE "LABPROD"."SP_VAC_INSERTARPERIODOANT" 
(
  KEYEMP IN NUMBER,
  FECINI IN DATE,
  FECING IN DATE,
  KEYPRO IN INTEGER,
  KEYLOC IN VARCHAR2,
  NUMANI OUT NUMBER
) AS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
ANTIGUEDAD DECIMAL(10,2);
DIADER DECIMAL(10,2);
KEYTAB VARCHAR2(6);
FECCAD DATE;
BEGIN
  --Buscar si el periodo anticipado ya fue creado
  BEGIN
    SELECT DIA_NUMANI INTO NUMANI
      FROM LABPROD.MOLODIAD
      WHERE DIA_KEYEMP = KEYEMP
        AND DIA_FECINI = FECINI;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NUMANI := 0;
  END;
  IF NUMANI > 0 THEN
    DBMS_OUTPUT.PUT_LINE('PERIODO YA EXISTE NUMANI = '||NUMANI);
    RETURN;
  END IF;
  KEYTAB := LABPROD.FN_VAC_TABLADIAS(KEYPRO,KEYLOC);
  DBMS_OUTPUT.PUT_LINE('KEYTAB = '||KEYTAB);
  DIADER := LABPROD.FN_VAC_DIASDERECHO(KEYEMP,FECING,FECINI,KEYPRO,KEYTAB);
  DBMS_OUTPUT.PUT_LINE('DIADER = '||DIADER);
  FECCAD := ADD_MONTHS(FECINI,18) - 1;
  BEGIN
    INSERT INTO LABPROD.MOLODIAD (DIA_KEYEMP,DIA_KEYCON,DIA_DIADER,DIA_FECINI,DIA_FECCAD,DIA_DIAANT,DIA_KEYUSU,DIA_FECACT,DIA_DIASAL,DIA_NUMANI)
      VALUES (KEYEMP,'VA',DIADER,FECINI,FECCAD,0,KEYEMP,SYSDATE,DIADER,YEAR(FECINI));
    NUMANI := YEAR(FECINI);
  EXCEPTION
    WHEN OTHERS THEN
      NUMANI := 0;
  END;
END SP_VAC_INSERTARPERIODOANT;
/
