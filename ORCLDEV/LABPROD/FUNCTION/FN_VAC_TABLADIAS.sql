CREATE OR REPLACE NONEDITIONABLE FUNCTION "LABPROD"."FN_VAC_TABLADIAS" 
(
  KEYPRO IN INTEGER
,  KEYLOC IN VARCHAR2
) RETURN VARCHAR2 AS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
KEYTAB VARCHAR2(6);
BEGIN
  BEGIN
    SELECT PAM_FOLFIN INTO KEYTAB
			FROM LABPROD.GLCOPAMS WHERE PAM_KEYPAR = 'TTV' AND PAM_NOMPAR = 'TABLA DE VACACIONES' AND PAM_CVESEC = to_char(KEYPRO);
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
    KEYTAB := '';
  END;
  RETURN KEYTAB;
END FN_VAC_TABLADIAS;
