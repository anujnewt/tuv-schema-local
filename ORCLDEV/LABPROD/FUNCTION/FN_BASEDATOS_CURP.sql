CREATE OR REPLACE NONEDITIONABLE FUNCTION "LABPROD"."FN_BASEDATOS_CURP" 
(
  CURP IN VARCHAR2
) RETURN VARCHAR2 AS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
RESULTADO VARCHAR2(10);
KEYPRO NUMBER;
STATUS NUMBER;
BASE VARCHAR(10);
BEGIN
  BEGIN
  RETURN 'TVNOMINA';
  BASE := 'TELECOM';
  FOR q_empleado IN
  (
    SELECT CASE WHEN PAM_CVESEC IS NULL THEN 'TVNOMINA' ELSE 'TELECOM' END BASE, EMP_KEYPRO,EMP_STATUS,EMP_FECMOD
    FROM LABPROD.NMCOEMPL
    LEFT JOIN LABPROD.GLCOPAMS ON PAM_KEYPAR = 'SEPB' AND EMP_KEYPRO = PAM_CVESEC
    WHERE EMP_RECURP = CURP
	ORDER BY EMP_STATUS
    /*
    APSI 231017
    UNION ALL
    SELECT CASE WHEN PAM_CVESEC IS NULL THEN 'TVNOMINA' ELSE 'TELECOM' END BASE, EMP_KEYPRO,EMP_STATUS,EMP_FECMOD
    FROM LABPROD.NMCOEMPL@RTELECOM
    LEFT JOIN LABPROD.GLCOPAMS ON PAM_KEYPAR = 'SEPB' AND EMP_KEYPRO = PAM_CVESEC
    WHERE EMP_RECURP = CURP
    ORDER BY EMP_STATUS,EMP_FECMOD
    */
    )
  LOOP
    BASE := q_empleado.BASE;
    KEYPRO := q_empleado.emp_keypro;
    STATUS := q_empleado.emp_status;
    EXIT;
  END LOOP;
  COMMIT;
  RETURN BASE;
  EXCEPTION
    WHEN OTHERS THEN
      RETURN 'TVNOMINA';
  END;
END FN_BASEDATOS_CURP;
