CREATE OR REPLACE FORCE NONEDITIONABLE VIEW "LABPROD"."EMPLEADOS_COV_V" ("EMP_KEYEMP", "EMP_RECURP", "EMP_REGIMS", "EMP_STATUS", "EMP_CTABAN", "CTA_CTABAN", "PAM_NOMPAR", "EMP_NOMEMP") AS 
  select  T1.EMP_KEYEMP  ,
          T1.EMP_RECURP  ,
          T1.EMP_REGIMS  ,
          T1.EMP_STATUS  ,
          T1.EMP_CTABAN  ,
          T2.CTA_CTABAN  ,
          T3.PAM_NOMPAR  ,
          T1.EMP_NOMEMP
   from LABPROD.NMLOCTAS T2,
        LABPROD.NMCOEMPL T1,
        LABPROD.GLCOPAMS T3
  where  'FP' = T3.PAM_KEYPAR(+)
          and T1.EMP_FORPAG = T3.PAM_CVESEC(+)
          and T1.EMP_KEYEMP = T2.CTA_KEYEMP
          and T1.EMP_KEYPRO = T2.CTA_KEYPRO
          and T1.EMP_STATUS = 1
          and T1.EMP_KEYPRO <> 6;
