CREATE OR REPLACE FORCE NONEDITIONABLE VIEW "LABPROD"."SVWNOM_EMPLEADOS_V" ("NO_EMPLEADO", "NOMBRE", "APE_PATERNO", "APE_MATERNO", "CLAVE_COSTOS", "DESC_COSTOS", "CLAVE_LOCALIDAD", "DESC_LOCALIDAD", "CLAVE_PROCESO", "DESC_PROCESO", "CLAVE_COMPANIA", "DESC_COMPANIA", "CLAVE_PUESTO", "DESC_PUESTO", "ESTATUS") AS 
  SELECT EMP_KEYEMP "NO_EMPLEADO"
           ,SUBSTR(EMP_NOMEMP,INSTR(EMP_NOMEMP,'/',1,2) +1,LENGTH(EMP_NOMEMP) - INSTR(EMP_NOMEMP,'/',1,2)) "NOMBRE"
     ,SUBSTR(EMP_NOMEMP,0,INSTR(EMP_NOMEMP,'/',1,1)-1) "APE_PATERNO"
     ,SUBSTR(EMP_NOMEMP,INSTR(EMP_NOMEMP,'/',1,1)+1,INSTR(EMP_NOMEMP,'/',1,2) - instr(EMP_NOMEMP,'/',1,1)-1) "APE_MATERNO"
     ,CEN_KEYCEN "CLAVE_COSTOS"
     ,CEN_DESCEN "DESC_COSTOS"
     ,LOC_KEYLOC "CLAVE_LOCALIDAD"
     ,LOC_DESLOC "DESC_LOCALIDAD"
     ,PRO_KEYPRO "CLAVE_PROCESO"
     ,PRO_DESPRO "DESC_PROCESO"
     ,(SELECT CIA_KEYCIA FROM LABPROD.NMLOCIAS WHERE CIA_KEYCIA=PRO_KEYCIA) "CLAVE_COMPANIA"
     ,(SELECT CIA_DESCIA FROM LABPROD.NMLOCIAS WHERE CIA_KEYCIA=PRO_KEYCIA) "DESC_COMPANIA"
     ,PUE_KEYPUE "CLAVE_PUESTO"
     ,PUE_DESPUE "DESC_PUESTO"
     ,CASE EMP_STATUS
       WHEN 1 THEN ' 1- ACTIVO'
        WHEN 2 THEN '2- INACTIVO'
        ELSE 'OTRO'
       END "ESTATUS"
  FROM LABPROD.NMCOEMPL
      ,LABPROD.NMLOCENC
      ,LABPROD.NMLOLOCP
      ,LABPROD.NMLOPROC
      ,LABPROD.NMCOPUES
  WHERE EMP_KEYCEN=CEN_KEYCEN
  AND EMP_KEYPRO =PRO_KEYPRO
  AND EMP_KEYLOC = LOC_KEYLOC
  AND EMP_KEYPUE=PUE_KEYPUE
  ORDER BY EMP_KEYEMP  DESC
  ;
