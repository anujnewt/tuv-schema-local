CREATE OR REPLACE NONEDITIONABLE TRIGGER "XX_BLOQUEOBAJAS"."NOTIFICACIONES_INSERT" 
  BEFORE INSERT ON XX_BLOQUEOBAJAS.NOTIFICACIONES
  FOR EACH ROW
BEGIN
  SELECT XX_BLOQUEOBAJAS.NOTIFICACIONES_SEQ.nextval
  INTO :new.IDNOTIFICACION
  FROM dual;
END;


/
ALTER TRIGGER "XX_BLOQUEOBAJAS"."NOTIFICACIONES_INSERT" ENABLE;
