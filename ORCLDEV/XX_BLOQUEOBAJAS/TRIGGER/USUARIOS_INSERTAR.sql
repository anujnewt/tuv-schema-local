CREATE OR REPLACE NONEDITIONABLE TRIGGER "XX_BLOQUEOBAJAS"."USUARIOS_INSERTAR" 
  BEFORE INSERT ON XX_BLOQUEOBAJAS.USUARIOEMPLEADO
  FOR EACH ROW
BEGIN
  SELECT XX_BLOQUEOBAJAS.USUARIO_SEQ.nextval
  INTO :new.IDUSUARIO
  FROM dual;
END;


/
ALTER TRIGGER "XX_BLOQUEOBAJAS"."USUARIOS_INSERTAR" ENABLE;
