            NVL(E.DESCRIPCION,'<SIN DESCRIPCION>') DESCRIPCION,
            'I',E.PLATAFORMA
    FROM    FECXC_DEP_ESPECIALES E,
            FECXC_DEP_ESPECIALES_D D,
            FECXP_CLA_FE_NOCHEQUERA P,
            FECXC_EMPRESAS C,
            FECXP_MONEDAS M
    WHERE    E.ID_TIPO_OPERACION_SET =4103
    AND      E.FEC_VALOR  BETWEEN V_FECHA_INI     AND V_V_FECHA_FIN
    AND      E.NO_EMPRESA BETWEEN V_ECODIGO_DESDE AND V_ECODIGO_HASTA
    AND      E.SECUENCIA_DEP_ESPECIALES = D.SECUENCIA_DEP_ESPECIALES (+)
    AND      P.TIPO_OPERACION = E.ID_TIPO_OPERACION_SET
    AND      P.ID_TIPO_MOVTO = 'I'
    AND      P.TIPO_CLAVE = 'IN'
    AND      E.NO_EMPRESA = C.E_CODIGO
    AND      C.CUAL_ERP = 'O'
    AND      M.MON_SET = E.ID_DIVISA
    AND      TO_NUMBER (TO_CHAR (E.FEC_VALOR, 'MM')) = M.MES
    AND      TO_NUMBER (TO_CHAR (E.FEC_VALOR, 'YYYY')) = M.PERIODO
    ;
    ---- Clasificar los egresos
    --- 2.1 Obtener el regreso de inversi?n 4102 y el inter?s ganado
    INSERT  INTO FECXP_DET_REALES_INVERSION (
            E_CODIGO, FOLIO_SET, TIPO_OPERACION,ESTATUS_MOVIMIENTO, SECUENCIA_ID, CLA_FE_ID, CLA_FE_DES,
            ID_CHEQUERA,ID_BANCO,FORMA_PAGO,FECHA_APLICACION,MONEDA,TIPO_CAMBIO,IMPORTE,
            NUMERO_DE_PARTIDA_ERP,ORA_SOIN_SEGMENTO1, ORA_SOIN_SEGMENTO2, ORA_SOIN_SEGMENTO3, ORACLE_SEGMENTO4, ORACLE_SEGMENTO5, ORACLE_SEGMENTO6, ORACLE_SEGMENTO7,
            IMPORTE_LINEA,CONCEPTO,BENEFICIARIO,NO_CLIENTE,REFERENCIA,DESCRIPCION,ID_TIPO_MOVTO,TIPO_ERP)
    SELECT  E.NO_EMPRESA, E.NO_FOLIO_DET, E.ID_TIPO_OPERACION_SET,E.ID_STATUS_MOV, E.SECUENCIA_DEP_ESPECIALES,P.CLA_FE_ID,P.CLA_FE_DES,
            E.ID_CHEQUERA, E.ID_BANCO,E.ID_FORMA_PAGO, E.FEC_VALOR, E.ID_DIVISA, E.TIPO_CAMBIO,E.IMPORTE,
            0,
            NVL(D.ORA_SOIN_SEGMENTO1, '000') ORA_SOIN_SEGMENTO1,  --segmento 1
            NVL(D.ORA_SOIN_SEGMENTO2, '00') ORA_SOIN_SEGMENTO2,
            NVL(D.ORA_SOIN_SEGMENTO3, '000') ORA_SOIN_SEGMENTO3,
            NVL(D.ORACLE_SEGMENTO4, '000000') ORA_SOIN_SEGMENTO4,
            NVL(D.ORACLE_SEGMENTO5, '00000000') ORA_SOIN_SEGMENTO5,
            NVL(D.ORACLE_SEGMENTO6, '000') ORA_SOIN_SEGMENTO6,
            NVL(D.ORACLE_SEGMENTO7, '0') ORA_SOIN_SEGMENTO7,
            CASE WHEN E.ID_TIPO_OPERACION_SET=4103 THEN TO_NUMBER(P.CLA_ATRIBUTO3) ELSE 1 END * NVL(D.IMPORTE_LINEA, E.IMPORTE) IMPORTE_LINEA,
            E.CONCEPTO, E.BENEFICIARIO,E.NO_CLIENTE,
            NVL(E.REFERENCIA, '<SIN REFERENCIA>') REFERENCIA,
            NVL(E.DESCRIPCION,'<SIN DESCRIPCION>') DESCRIPCION,
            'E',E.PLATAFORMA
    FROM    FECXC_DEP_ESPECIALES E,
            FECXC_DEP_ESPECIALES_D D,
            FECXP_CLA_FE_NOCHEQUERA P,
            FECXC_EMPRESAS C,
            FECXP_MONEDAS M
    WHERE    E.ID_TIPO_OPERACION_SET in (4102,4103)
    AND      E.FEC_VALOR  BETWEEN V_FECHA_INI     AND V_V_FECHA_FIN
    AND      E.NO_EMPRESA BETWEEN V_ECODIGO_DESDE AND V_ECODIGO_HASTA
    AND      E.SECUENCIA_DEP_ESPECIALES = D.SECUENCIA_DEP_ESPECIALES (+)
    AND      P.TIPO_OPERACION = E.ID_TIPO_OPERACION_SET
    AND      P.ID_TIPO_MOVTO = 'E'
    AND      P.TIPO_CLAVE = 'IN'
    AND      E.NO_EMPRESA = C.E_CODIGO
    AND      C.CUAL_ERP = 'O'
    AND      M.MON_SET = E.ID_DIVISA
    AND      TO_NUMBER (TO_CHAR (E.FEC_VALOR, 'MM')) = M.MES
    AND      TO_NUMBER (TO_CHAR (E.FEC_VALOR, 'YYYY')) = M.PERIODO
    AND      C.CUAL_ERP = 'O'
    ;
    --2.2 Obtener el ISR oracle como egreso
    INSERT    INTO FECXP_DET_REALES_INVERSION (
            E_CODIGO, FOLIO_SET, TIPO_OPERACION,ESTATUS_MOVIMIENTO, SECUENCIA_ID, CLA_FE_ID, CLA_FE_DES,
            ID_CHEQUERA,ID_BANCO,FORMA_PAGO,FECHA_APLICACION,MONEDA,TIPO_CAMBIO,IMPORTE,
            NUMERO_DE_PARTIDA_ERP,ORA_SOIN_SEGMENTO1, ORA_SOIN_SEGMENTO2, ORA_SOIN_SEGMENTO3, ORACLE_SEGMENTO4, ORACLE_SEGMENTO5, ORACLE_SEGMENTO6, ORACLE_SEGMENTO7,
            IMPORTE_LINEA,CONCEPTO,BENEFICIARIO,NO_CLIENTE,REFERENCIA,DESCRIPCION,ID_TIPO_MOVTO,TIPO_ERP)
    SELECT  E.E_CODIGO, E.FOLIO_SET, E.TIPO_OPERACION,E.ESTATUS_MOVIMIENTO, E.SECUENCIA_PAGOS_ERP,P.CLA_FE_ID,P.CLA_FE_DES,
            E.ID_CHEQUERA, E.ID_BANCO,E.FORMA_PAGO, E.FECHA_APLICACION, E.MONEDA, E.TIPO_CAMBIO,
            CASE WHEN E.ESTATUS_MOVIMIENTO IN ('X', 'Y', 'Z') THEN -1 ELSE 1 END * E.IMPORTE IMPORTE,
            D.NUMERO_DE_PARTIDA_ERP, D.ORACLE_SEGMENTO1, D.ORACLE_SEGMENTO2, D.ORACLE_SEGMENTO3, D.ORACLE_SEGMENTO4, D.ORACLE_SEGMENTO5, D.ORACLE_SEGMENTO6, D.ORACLE_SEGMENTO7,
            D.IMPORTE_LINEA * TO_NUMBER(P.CLA_ATRIBUTO3) IMPORTE_LINEA ,E.CONCEPTO, E.BENEFICIARIO,E.NO_CLIENTE,NVL(E.REFERENCIA,'<SIN REFERENCIA>') REFERENCIA, NVL(E.DESCRIPCION,'<SIN DESCRIPCION>') DESCRIPCION,
            'E','O'
    FROM     FECXP_ENC_PAGOS_ERP E,
            FECXP_DET_PAGOS_PROCESADOS D,
            FECXP_CLA_FE_NOCHEQUERA P,
            FECXC_EMPRESAS C,
            FECXP_MONEDAS M
    WHERE   E.E_CODIGO = NVL (V_E_CODIGO, E.E_CODIGO)
    AND     E.TIPO_OPERACION =4104
    AND     E.FECHA_APLICACION BETWEEN V_FECHA_INI     AND V_V_FECHA_FIN
    AND     E.E_CODIGO         BETWEEN V_ECODIGO_DESDE AND V_ECODIGO_HASTA
    AND     E.E_CODIGO = D.E_CODIGO
    AND     E.SECUENCIA_PAGOS_ERP = D.SECUENCIA_PAGOS_ERP
    AND     P.TIPO_OPERACION = E.TIPO_OPERACION
    AND     P.ID_TIPO_MOVTO = 'E'
    AND     P.TIPO_CLAVE = 'IN'
    AND     C.E_CODIGO = E.E_CODIGO
    AND     M.MON_SET = E.MONEDA
    AND     TO_NUMBER (TO_CHAR (E.FECHA_APLICACION, 'MM')) = M.MES
    AND     TO_NUMBER (TO_CHAR (E.FECHA_APLICACION, 'YYYY')) = M.PERIODO
    AND     C.CUAL_ERP = 'O'
    ;
    --===============================================================================================--
    --== TERMINA REAL ==--
    ---/* Se agrega codigo para eliminar los duplicados SALVO BUEN COBRO  de ORACLE */-------
   DELETE FECXC.FECXP_INGRESOS_CLASIF WHERE FOLIO_SET IN(
                                                        SELECT FOLIO_SET FROM FECXC.FECXP_INGRESOS_CLASIF
                                                        WHERE FECHA BETWEEN TO_DATE('01/JAN/'||TO_CHAR(SYSDATE,'YYYY')) AND  TO_DATE('31/DEC/'||TO_CHAR(SYSDATE,'YYYY'))
                                                        AND CONCEPTO ='DEP S B COBRO'
                                                        AND CUAL_ERP='O'
                                                        GROUP BY
                                                                   /*CLA_FE_ID,*/ E_CODIGO, FOLIO_SET,
                                                                   /*TIPO_OPERACION, FECHA,*/ MONEDA,
                                                                   TIPO_CAMBIO, IMPORTE, CONCEPTO,
                                                                   /*BENEFICIARIO, /*ID_STATUS_MOV, ID_CHEQUERA,*/
                                                                   /*ID_BANCO,ID_FORMA_PAGO, REFERENCIA,*/
                                                                   IMPORTE_LINEA, /*ORA_SOIN_SEGMENTO1, ORA_SOIN_SEGMENTO2,
                                                                   ORA_SOIN_SEGMENTO3, ORACLE_SEGMENTO4, ORACLE_SEGMENTO5,
                                                                   ORACLE_SEGMENTO6, ORACLE_SEGMENTO7,*/ CUAL_ERP
                                                                   /*TIPO_CLASIFICACION, NO_CLIENTE/*, DESCRIPCION*/
                                                           HAVING COUNT(*) > 1)
                                                 AND  ID_STATUS_MOV='P';
       -------------SE AGREGRA CODIGO PARA CAMBIAR DE SIGNO LOS FOLIOS CANCELADOS ---------------------
        FOR C1 IN FOLIOS_REPETIDOS LOOP
        IF C1.IMPORTE >=0 AND C1.IMPORTE_LINEA <0 THEN
          UPDATE FECXC.FECXP_INGRESOS_CLASIF
            SET IMPORTE_LINEA=(C1.IMPORTE_LINEA*-1)
            WHERE FOLIO_SET= C1.FOLIO_SET
            AND   IMPORTE_LINEA  = C1.IMPORTE_LINEA
            AND   ID_STATUS_MOV='X' ;
            --DBMS_OUTPUT.PUT_LINE('IMPORTE POSITIVO -> '||C1.IMPORTE||' IMPORTE LINEA -> '||C1.IMPORTE_LINEA);
        END IF;
        IF C1.IMPORTE <0 AND C1.IMPORTE_LINEA >=0 THEN
          UPDATE FECXC.FECXP_INGRESOS_CLASIF
            SET IMPORTE_LINEA=(C1.IMPORTE_LINEA*-1)
            WHERE FOLIO_SET= C1.FOLIO_SET
            AND   IMPORTE_LINEA  = C1.IMPORTE_LINEA
            AND   ID_STATUS_MOV='X' ;
             --DBMS_OUTPUT.PUT_LINE('IMPORTE NEGATIVO -> '||C1.IMPORTE||' IMPORTE LINEA -> '||C1.IMPORTE_LINEA);
        END IF;
     END LOOP;
    COMMIT;
    /*
    --Se agrega el proceso de aperturacion de folios de ingresos
    --12-ENE-2012 Se desactiva aperturacion CXC (en los procesos automaticos)
    */
    IF V_TIPO_EJECUCION = 1 THEN
        NULL;
    ELSE
        BEGIN
         fecxc.fecxp_base_iva_intermpresas(V_FECHA_INI,V_V_FECHA_FIN);
        END;
    END IF;
    EXCEPTION
    WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20000,'NO HAY DATOS NUEVOS.');
    WHEN OTHERS THEN
       ROLLBACK;
       RAISE_APPLICATION_ERROR(-20000,'Error:' || SQLCODE || ' - ' || SQLERRM);
END FECXP_LLENA_DET_REAL_ERP;
