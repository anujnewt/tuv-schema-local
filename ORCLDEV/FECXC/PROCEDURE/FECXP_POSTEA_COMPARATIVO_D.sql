CREATE OR REPLACE EDITIONABLE PROCEDURE "FECXC"."FECXP_POSTEA_COMPARATIVO_D" (
	V_AGRUPAMIENTO_STR_1 IN VARCHAR2,
	V_AGRUPAMIENTO_STR_2 IN VARCHAR2,
	V_AGRUPAMIENTO_STR_3 IN VARCHAR2
)
IS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
-- DECLARE
	V_AGRUPAMIENTO_1 VARCHAR2 (255):= '';
	V_AGRUPAMIENTO_2 VARCHAR2 (255):= '';
	V_AGRUPAMIENTO_3 VARCHAR2 (255):= '';
	V_ORDEN_AGRUPAMIENTO_1 INT:= TO_NUMBER (SUBSTR (V_AGRUPAMIENTO_STR_1, 13, 1)) - 3;
	V_ORDEN_AGRUPAMIENTO_2 INT:= TO_NUMBER (SUBSTR (V_AGRUPAMIENTO_STR_2, 13, 1)) - 3;
	V_ORDEN_AGRUPAMIENTO_3 INT:= TO_NUMBER (SUBSTR (V_AGRUPAMIENTO_STR_3, 13, 1)) - 3;
	TYPE CLA_FE_TYP IS REF CURSOR;
	CURSOR_CLASIFICACION_FE   CLA_FE_TYP;
	CLA_FE_REC  FECXP_CLASIFICACION_FE%ROWTYPE;
	V_SQL_CURSOR VARCHAR2(2000);
	V_SQL_INSERT VARCHAR2(2000);
  	V_HOY DATE:= SYSDATE;
	V_MES_ACT INTEGER;
	V_SALDO_FINAL_REAL VARCHAR2 (25):= 'SF';
	V_SALDO_FINAL_PPTO VARCHAR2 (25):= 'SF';
	V_DIA_D			   DATE:=TO_DATE(TO_CHAR(ADD_MONTHS (SYSDATE, -1),'YYYYMM')||'01','YYYYMMDD');
	V_SESION VARCHAR2 (25):= 'SESION';
	V_FACTOR NUMBER:= 1000;
	V_FACTOR_TITULO VARCHAR2 (100);
	V_RUBRO FECXP_CLASIFICACION_FE.CLA_ATRIBUTO2%TYPE;
	V_MES_FIN DATE;
	V_E_CODIGO INT;
BEGIN
	V_MES_FIN := V_HOY;
 	DELETE FECXP_POSTEO_COMPARACION_D_TMP;
	DELETE FECXP_POSTEO
	WHERE	XML_DOC = 'CE_FE_003.xml';
	-----------------------------------------------------------------------------------------
	-- METE SALDOS INICIALES REALES PPTOS
	INSERT	INTO FECXP_POSTEO_COMPARACION_D_TMP (FECHA, ORDEN, CLA_ATRIBUTO2, CLA_FE_ID, CLA_FE_DES, MONTO_REAL, MONTO_PPTO, MONTO_VAR, SESION)
	SELECT	TO_DATE (TO_CHAR (C.PERIODO) || LPAD (C.MES, 2, '0') || '01', 'YYYYMMDD'), TO_NUMBER (CF.CLA_ATRIBUTO3), CF.CLA_ATRIBUTO2, C.CLA_FE_ID, C.CLA_FE_DES, ROUND (SUM (C.IMPORTE_LINEA * M.TIPO_CAMBIO / V_FACTOR)), ROUND (SUM (C.IMPORTE_LINEA * M.TIPO_CAMBIO / V_FACTOR)), 0, V_SESION
	FROM	FECXP_MONEDAS M,
			FECXP_CLASIFICACION_FE CF,
			FECXP_PPTO_CARATULA C,
			FECXC_EMP_X_SEGMENTO A
	WHERE	C.CLA_FE_ID = 'SI'
	AND		C.E_CODIGO = A.E_CODIGO
	AND		C.PERIODO >= TO_NUMBER (TO_CHAR (V_DIA_D, 'YYYY'))
	AND		C.MES >= TO_NUMBER (TO_CHAR (V_DIA_D, 'MM'))
	AND		C.CLA_FE_ID = CF.CLA_FE_ID
	AND		C.E_CODIGO = NVL (V_E_CODIGO, C.E_CODIGO)
	AND		A.ID_SEGMENTO = 23
	AND		M.MON_ORACLE = C.MONEDA
	AND		M.PERIODO = C.PERIODO
	AND		M.MES = C.MES
	GROUP BY TO_DATE (TO_CHAR (C.PERIODO) || LPAD (C.MES, 2, '0') || '01', 'YYYYMMDD'), TO_NUMBER (CF.CLA_ATRIBUTO3), CF.CLA_ATRIBUTO2, C.CLA_FE_ID, C.CLA_FE_DES;
	-----------------------------------------------------------------------------------------
	-- METE SALDOS FINALES REALES PPTOS
	INSERT	INTO FECXP_POSTEO_COMPARACION_D_TMP (FECHA, ORDEN, CLA_ATRIBUTO2, CLA_FE_ID, CLA_FE_DES, MONTO_REAL, MONTO_PPTO, MONTO_VAR, SESION)
	SELECT	C.FECHA, TO_NUMBER (CF.CLA_ATRIBUTO3), CF.CLA_ATRIBUTO2, C.CLA_FE_ID, CF.CLA_FE_DES, ROUND (SUM (C.IMPORTE_LINEA * M.TIPO_CAMBIO / V_FACTOR)), 0, ROUND (SUM (C.IMPORTE_LINEA * M.TIPO_CAMBIO / V_FACTOR)), V_SESION
	FROM	FECXP_MONEDAS M,
			FECXP_CLASIFICACION_FE CF,
			FECXP_REAL_CARATULAD C,
			FECXC_EMP_X_SEGMENTO A
	WHERE	A.ID_SEGMENTO = 23
	AND		C.E_CODIGO = A.E_CODIGO
	AND		C.CLA_FE_ID = V_SALDO_FINAL_REAL
	AND		C.FECHA >= V_DIA_D
	AND		C.FECHA <= V_HOY
	AND		C.E_CODIGO = NVL (V_E_CODIGO, C.E_CODIGO)
	AND		C.CLA_FE_ID = CF.CLA_FE_ID
	AND		M.MON_ORACLE = C.MONEDA
	AND		M.PERIODO = TO_NUMBER (TO_CHAR (C.FECHA, 'YYYY'))
	AND		M.MES = TO_NUMBER (TO_CHAR (C.FECHA, 'MM'))
	GROUP BY C.FECHA, TO_NUMBER (CF.CLA_ATRIBUTO3), CF.CLA_ATRIBUTO2, C.CLA_FE_ID, CF.CLA_FE_DES;
	INSERT	INTO FECXP_POSTEO_COMPARACION_D_TMP (FECHA, ORDEN, CLA_ATRIBUTO2, CLA_FE_ID, CLA_FE_DES, MONTO_REAL, MONTO_PPTO, MONTO_VAR, SESION)
	SELECT	TO_DATE (TO_CHAR (C.PERIODO) || LPAD (C.MES, 2, '0') || '01', 'YYYYMMDD'), TO_NUMBER (CF.CLA_ATRIBUTO3), CF.CLA_ATRIBUTO2, C.CLA_FE_ID, CF.CLA_FE_DES, 0, ROUND (SUM (C.IMPORTE_LINEA * M.TIPO_CAMBIO / V_FACTOR)), -1 * ROUND (SUM (C.IMPORTE_LINEA * M.TIPO_CAMBIO / V_FACTOR)), V_SESION
	FROM	FECXP_MONEDAS M,
			FECXP_CLASIFICACION_FE CF,
			FECXP_PPTO_CARATULA C,
			FECXC_EMP_X_SEGMENTO A
	WHERE	A.ID_SEGMENTO = 23
	AND		C.E_CODIGO = A.E_CODIGO
	AND		C.CLA_FE_ID = V_SALDO_FINAL_REAL
	AND		C.PERIODO >= TO_NUMBER (TO_CHAR (V_DIA_D, 'YYYY'))
	AND		C.MES >= TO_NUMBER (TO_CHAR (V_DIA_D, 'MM'))
	AND		C.PERIODO <= TO_NUMBER (TO_CHAR (V_HOY, 'YYYY'))
	AND		C.MES <= TO_NUMBER (TO_CHAR (V_HOY, 'MM'))
	AND		C.E_CODIGO = NVL (V_E_CODIGO, C.E_CODIGO)
	AND		C.CLA_FE_ID = CF.CLA_FE_ID
	AND		M.MON_ORACLE = C.MONEDA
	AND		M.PERIODO = C.PERIODO
	AND		M.MES = C.MES
	GROUP BY TO_DATE (TO_CHAR (C.PERIODO) || LPAD (C.MES, 2, '0') || '01', 'YYYYMMDD'), TO_NUMBER (CF.CLA_ATRIBUTO3), CF.CLA_ATRIBUTO2, C.CLA_FE_ID, CF.CLA_FE_DES;
	-----------------------------------------------------------------------------------------
	-- METE MOVIMIENTOS CARULA REALES PPTOS
	INSERT	INTO FECXP_POSTEO_COMPARACION_D_TMP (FECHA, ORDEN, CLA_ATRIBUTO2, CLA_FE_ID, CLA_FE_DES, MONTO_REAL, MONTO_PPTO, MONTO_VAR, SESION)
	SELECT	C.FECHA, TO_NUMBER (CF.CLA_ATRIBUTO3), CF.CLA_ATRIBUTO2, C.CLA_FE_ID, CF.CLA_FE_DES, ROUND (SUM (C.IMPORTE_LINEA * M.TIPO_CAMBIO / V_FACTOR)), 0, ROUND (SUM (C.IMPORTE_LINEA * M.TIPO_CAMBIO / V_FACTOR)), V_SESION
	FROM	FECXP_MONEDAS M,
			FECXP_CLASIFICACION_FE CF,
			FECXP_REAL_CARATULAD C,
			FECXC_EMP_X_SEGMENTO A
	WHERE	A.ID_SEGMENTO = 23
	AND		C.E_CODIGO = A.E_CODIGO
	AND		C.CLA_FE_ID NOT IN ('SI', 'SF')
	AND		C.CLA_FE_ID <> V_SALDO_FINAL_REAL
	AND		C.FECHA >= V_DIA_D
	AND		C.FECHA <= V_HOY
	AND		C.E_CODIGO = NVL (V_E_CODIGO, C.E_CODIGO)
	AND		C.CLA_FE_ID = CF.CLA_FE_ID
	AND		M.MON_ORACLE = C.MONEDA
	AND		M.PERIODO = TO_NUMBER (TO_CHAR (C.FECHA, 'YYYY'))
	AND		M.MES = TO_NUMBER (TO_CHAR (C.FECHA, 'MM'))
	GROUP BY C.FECHA, TO_NUMBER (CF.CLA_ATRIBUTO3), CF.CLA_ATRIBUTO2, C.CLA_FE_ID, CF.CLA_FE_DES;
	INSERT	INTO FECXP_POSTEO_COMPARACION_D_TMP (FECHA, ORDEN, CLA_ATRIBUTO2, CLA_FE_ID, CLA_FE_DES, MONTO_REAL, MONTO_PPTO, MONTO_VAR, SESION)
	SELECT	TO_DATE (TO_CHAR (C.PERIODO) || LPAD (C.MES, 2, '0') || '01', 'YYYYMMDD'), TO_NUMBER (CF.CLA_ATRIBUTO3), CF.CLA_ATRIBUTO2, C.CLA_FE_ID, CF.CLA_FE_DES, 0, ROUND (SUM (C.IMPORTE_LINEA * M.TIPO_CAMBIO / V_FACTOR)), -1 * ROUND (SUM (C.IMPORTE_LINEA * M.TIPO_CAMBIO / V_FACTOR)), V_SESION
	FROM	FECXP_MONEDAS M,
			FECXP_CLASIFICACION_FE CF,
			FECXP_PPTO_CARATULA C,
			FECXC_EMP_X_SEGMENTO A
	WHERE	A.ID_SEGMENTO = 23
	AND		C.E_CODIGO = A.E_CODIGO
	AND		C.CLA_FE_ID NOT IN ('SI', 'SF')
	AND		C.PERIODO >= TO_NUMBER (TO_CHAR (V_DIA_D, 'YYYY'))
	AND		C.MES >= TO_NUMBER (TO_CHAR (V_DIA_D, 'MM'))
	AND		C.E_CODIGO = NVL (V_E_CODIGO, C.E_CODIGO)
	AND		C.CLA_FE_ID = CF.CLA_FE_ID
	AND		M.MON_ORACLE = C.MONEDA
	AND		M.PERIODO = C.PERIODO
	AND		M.MES = C.MES
	GROUP BY TO_DATE (TO_CHAR (C.PERIODO) || LPAD (C.MES, 2, '0') || '01', 'YYYYMMDD'), TO_NUMBER (CF.CLA_ATRIBUTO3), CF.CLA_ATRIBUTO2, C.CLA_FE_ID, CF.CLA_FE_DES;
	V_FACTOR_TITULO:= CASE V_FACTOR
					  WHEN 1 THEN 'Montos en Pesos'
					  WHEN 100 THEN 'Cientos de Pesos'
					  WHEN 1000 THEN 'Miles de Pesos'
					  WHEN 1000000 THEN 'Millones de Pesos'
					  ELSE 'Montos x ' || V_FACTOR END;
-----------------------------------------------------------------------------------------
	-- GENERA XML  --
-----------------------------------------------------------------------------------------
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_003.xml', 'i>?<?xml version="1.0" encoding="UTF-8"?>', V_SESION);
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_003.xml', '<!DOCTYPE xliff PUBLIC "-//XLIFF//DTD XLIFF//EN" "http://www.oasis-open.org/committees/xliff/documents/xliff.dtd" >', V_SESION);
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_003.xml', '<xliff version="1.0" xml:lang="es">', V_SESION);
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_003.xml', ' <Encabezado Titulo = "Acumulado Reales Flujo de Efectivo Diario" Subtitulo = "'|| V_FACTOR_TITULO || ' nominales." Fecha = "' || TO_CHAR (SYSDATE, 'YYYYMMDD hh24mmss') || '">', V_SESION);
	V_SQL_CURSOR := 'SELECT C.CLA_ATRIBUTO4, C.CLA_ATRIBUTO5, C.CLA_ATRIBUTO6, C.CLA_ATRIBUTO2 FROM FECXP_CLASIFICACION_FE C, FECXP_POSTEO_COMPARACION_D_TMP T WHERE C.CLA_FE_ID = T.CLA_FE_ID AND TO_CHAR (T.FECHA, ''YYYYMMDD'') = ' || TO_CHAR (V_DIA_D, 'YYYYMMDD') || ' GROUP BY C.CLA_ATRIBUTO4, C.CLA_ATRIBUTO5, C.CLA_ATRIBUTO6, C.CLA_ATRIBUTO2 ORDER BY C.' || V_AGRUPAMIENTO_STR_1 || ', C.' || V_AGRUPAMIENTO_STR_2 || ', C.' || V_AGRUPAMIENTO_STR_3;
	LOOP
		--  <FECHA>  --
		INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION)
		VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_003.xml', '	<'|| TO_CHAR(V_DIA_D,'YYYYMMDD')  ||' >', V_SESION);
		OPEN CURSOR_CLASIFICACION_FE FOR V_SQL_CURSOR; -- USING MY_JOB;
		LOOP
			FETCH CURSOR_CLASIFICACION_FE
			INTO CLA_FE_REC.CLA_ATRIBUTO4, CLA_FE_REC.CLA_ATRIBUTO5, CLA_FE_REC.CLA_ATRIBUTO6, CLA_FE_REC.CLA_ATRIBUTO2 ;
			EXIT WHEN CURSOR_CLASIFICACION_FE%NOTFOUND;
			V_AGRUPAMIENTO_1:= CLA_FE_REC.CLA_ATRIBUTO4;
			V_AGRUPAMIENTO_2:= CLA_FE_REC.CLA_ATRIBUTO5;
			V_AGRUPAMIENTO_3:= CLA_FE_REC.CLA_ATRIBUTO6;
			V_RUBRO:= CLA_FE_REC.CLA_ATRIBUTO2;
			------------------------------------------------------------------------------------------------------------
			-- TI?ULO DEL RUBRO
			V_SQL_INSERT:= 'INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, ''CE_FE_002.xml'', ''		<Concepto Tipo = ''''T'''' Desc = '''''' || :' || V_ORDEN_AGRUPAMIENTO_1 || ' || '' > '' || :' || V_ORDEN_AGRUPAMIENTO_2 || ' || '' > '' || :' || V_ORDEN_AGRUPAMIENTO_3 || ' || '' > '' || :4 || ''''''<Concepto/>'', ''' || V_SESION || ''')';
			EXECUTE IMMEDIATE (V_SQL_INSERT)
			USING V_AGRUPAMIENTO_1, V_AGRUPAMIENTO_2, V_AGRUPAMIENTO_3, V_RUBRO;
			-- INSERT INTO FECXP_DEBUGUEA_STRING (SEC_STRING, SQL_STRING) VALUES (SEC_STRING.NEXTVAL, V_SQL_INSERT);
			------------------------------------------------------------------------------------------------------------
			-- DETALLE DEL RUBRO
			V_SQL_INSERT:=	 		   			'INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'SELECT	SEC_FECXP_POSTEO.NEXTVAL, ''CE_FE_002.xml'', T.XML_STRING, ''' || V_SESION ||  ''' ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'FROM	(';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		SELECT '' <Concepto Tipo = ''''L'''' Desc = '''''' || T.CLA_FE_DES || '' Real = '' || TO_CHAR (SUM (T.MONTO_REAL)) || '' Ppto = '' || TO_CHAR (SUM (T.MONTO_PPTO)) || '' Var = '' || TO_CHAR (SUM (T.MONTO_VAR)) || ''''''></Concepto>'' XML_STRING ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		FROM	FECXP_POSTEO_COMPARACION_D_TMP T, FECXP_CLASIFICACION_FE C ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		WHERE	T.CLA_FE_ID = C.CLA_FE_ID ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		TO_CHAR (T.FECHA, ''YYYYMMDD'') = ''' || V_DIA_D ||  ''' ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		T.SESION = ''' || V_SESION ||  ''' ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		T.CLA_ATRIBUTO2 = :1 ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		C.CLA_ATRIBUTO4 = :2 ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		C.CLA_ATRIBUTO5 = :3 ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		C.CLA_ATRIBUTO6 = :4 ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		GROUP BY TO_NUMBER (T.ORDEN), T.CLA_FE_DES ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		ORDER BY TO_NUMBER (T.ORDEN), T.CLA_FE_DES';
			V_SQL_INSERT:= V_SQL_INSERT ||		') T';
			EXECUTE IMMEDIATE (V_SQL_INSERT)
			USING V_RUBRO, V_AGRUPAMIENTO_1, V_AGRUPAMIENTO_2, V_AGRUPAMIENTO_3; --, V_SESION;
			-- INSERT INTO FECXP_DEBUGUEA_STRING (SEC_STRING, SQL_STRING) VALUES (SEC_STRING.NEXTVAL, V_AGRUPAMIENTO_1 || ', ' || V_AGRUPAMIENTO_2 || ', ' || V_AGRUPAMIENTO_3 || ', ' || V_RUBRO  || ' -- ' || V_SQL_INSERT);
			------------------------------------------------------------------------------------------------------------
			-- CORTE DEL RUBRO
			V_SQL_INSERT:=	 		   			'INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'SELECT	SEC_FECXP_POSTEO.NEXTVAL, ''CE_FE_002.xml'', T.XML_STRING, ''' || V_SESION ||  ''' ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'FROM	(';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		SELECT '' <Concepto Tipo = ''''C'''' Desc = ''''TOTAL '' || T.CLA_ATRIBUTO2 || '' Real = '' || TO_CHAR (SUM (T.MONTO_REAL)) || '' Ppto = '' || TO_CHAR (SUM (T.MONTO_PPTO)) || '' Var = '' || TO_CHAR (SUM (T.MONTO_VAR)) || ''''''></Concepto>'' XML_STRING ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		FROM	FECXP_POSTEO_COMPARACION_D_TMP T, FECXP_CLASIFICACION_FE C ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		WHERE	T.CLA_FE_ID = C.CLA_FE_ID ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		TO_CHAR (T.FECHA, ''YYYYMMDD'') = ''' || V_DIA_D ||  ''' ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		T.SESION = ''' || V_SESION ||  ''' ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		T.CLA_ATRIBUTO2 = :1 ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		C.CLA_ATRIBUTO4 = :2 ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		C.CLA_ATRIBUTO5 = :3 ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		AND		C.CLA_ATRIBUTO6 = :4 ';
			V_SQL_INSERT:= V_SQL_INSERT ||		'		GROUP BY T.CLA_ATRIBUTO2';
			V_SQL_INSERT:= V_SQL_INSERT ||		') T';
			EXECUTE IMMEDIATE (V_SQL_INSERT)
			USING V_RUBRO, V_AGRUPAMIENTO_1, V_AGRUPAMIENTO_2, V_AGRUPAMIENTO_3; --, V_SESION;
			-- INSERT INTO FECXP_DEBUGUEA_STRING (SEC_STRING, SQL_STRING) VALUES (SEC_STRING.NEXTVAL, V_AGRUPAMIENTO_1 || ', ' || V_AGRUPAMIENTO_2 || ', ' || V_AGRUPAMIENTO_3 || ', ' || V_RUBRO  || ' -- ' || V_SQL_INSERT);
		END LOOP;
		CLOSE	CURSOR_CLASIFICACION_FE;
		--  </FECHA>  --
		INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION)
		VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_003.xml', '	</'|| TO_CHAR(V_DIA_D,'YYYYMMDD')  ||'>', V_SESION);
		V_DIA_D := V_DIA_D +1;
		EXIT WHEN(TO_CHAR(V_HOY,'YYYYMMDD') = TO_CHAR(V_DIA_D,'YYYYMMDD'));
	END LOOP;
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_003.xml', '	</Encabezado>', V_SESION);
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_003.xml', '</xliff>', V_SESION);
	COMMIT;
-- END;
END FECXP_POSTEA_COMPARATIVO_D;
