                FROM    FECXP_ENC_PAGOS_ERP_TMP A
                WHERE    A.E_CODIGO = DEL_TABLE.E_CODIGO
                AND        A.SECUENCIA_PAGOS_ERP = DEL_TABLE.SECUENCIA_PAGOS_ERP
