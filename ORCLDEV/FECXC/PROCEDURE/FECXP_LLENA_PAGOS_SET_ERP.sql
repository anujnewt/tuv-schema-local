    -- SE INSERTA EL RESTO DE LOS FOLIOS QUE NO MANEJAN PROVISIONES --
    -- excluir a los folios cancelados y tomar solo aplicados
    INSERT    INTO FECXP_DET_PAGOS_PROCESADOS (
