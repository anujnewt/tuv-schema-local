    WHERE EXISTS
        (SELECT 1 FROM FECXP_REPLICAS_POR_CERRAR A WHERE A.E_CODIGO = UP_TABLE.E_CODIGO AND A.SECUENCIA_PAGOS_ERP = UP_TABLE.SECUENCIA_PAGOS_ERP)
