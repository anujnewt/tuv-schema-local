	WHERE	E.E_CODIGO = NVL (V_E_CODIGO, E.E_CODIGO)
    AND 	E.TIPO_OPERACION =4104
	AND		E.FECHA_APLICACION >= V_FECHA_INI
	AND		E.FECHA_APLICACION <= V_FECHA_FIN
	AND		E.E_CODIGO = D.E_CODIGO
	AND		E.SECUENCIA_PAGOS_ERP = D.SECUENCIA_PAGOS_ERP
    AND		P.TIPO_OPERACION = E.TIPO_OPERACION
    AND		P.ID_TIPO_MOVTO = 'E'
    AND		P.TIPO_CLAVE = 'IN'
    AND		C.E_CODIGO = E.E_CODIGO
    AND		M.MON_SET = E.MONEDA
    AND		TO_NUMBER (TO_CHAR (E.FECHA_APLICACION, 'MM')) = M.MES
	AND		TO_NUMBER (TO_CHAR (E.FECHA_APLICACION, 'YYYY')) = M.PERIODO
    AND		C.CUAL_ERP = 'O'
    ;
	--===============================================================================================--
	--== TERMINA REAL ==--
	--===============================================================================================--
	--== EMPIEZA PPTO ==--
	--== LIMPIA TABLA DE ENLACE  ==--
	DELETE	FECXP_REP_PPTO_COM_CTA_ERP -- FECXP_CTAS_CLASIF_PPTO_ERP; -- FECXP_CUENTAS_ERP_CARATULA MENOS (MONEDA, ID_SESION)
	WHERE	E_CODIGO = NVL (V_E_CODIGO, E_CODIGO)
	AND		CODE_COMBINATION_ID > 0;
	COMMIT;
	--== SE CARGAN LAS CUENTAS CONTABLES DEL PRESUPUESTO  ==--
	INSERT	INTO FECXP_REP_PPTO_COM_CTA_ERP (CLA_FE_ID, E_CODIGO, CODE_COMBINATION_ID, ORACLE_SEGMENTO1, ORACLE_SEGMENTO2, ORACLE_SEGMENTO3, ORACLE_SEGMENTO4, ORACLE_SEGMENTO5, ORACLE_SEGMENTO6, ORACLE_SEGMENTO7)
	SELECT	DISTINCT '|'AS CLA_FE_ID, E_CODIGO, CODE_COMBINATION, ORACLE_SEGMENTO1, ORACLE_SEGMENTO2, ORACLE_SEGMENTO3,ORACLE_SEGMENTO4, ORACLE_SEGMENTO5, ORACLE_SEGMENTO6, ORACLE_SEGMENTO7
	FROM	FECXP_PPTO_CONVERSION_ERP
	WHERE	E_CODIGO = NVL (V_E_CODIGO, E_CODIGO)
	AND		VERSION_FE = V_VERSION_FE
	AND		MES >= V_MES_DESDE;
	COMMIT;
	--==  CLASIFICACION DE CUENTAS SESGUN POLITICAS DE CLASIFICACION DE FE ==--
	OPEN	CURSOR_CLASIFICACION_FE_EGR;
	LOOP
		FETCH	CURSOR_CLASIFICACION_FE_EGR
		INTO	V_CLA_FE_ID, V_POLITICA_ERP_ID, V_PRIORIDAD, V_TIPO_OPERACION_INI, V_TIPO_OPERACION_FIN, V_ID_BANCO_INI, V_ID_BANCO_FIN, V_ID_CHEQUERA_INI, V_ID_CHEQUERA_FIN,
				V_ORA_S1_INI, V_ORA_S1_FIN, V_ORA_S2_INI, V_ORA_S2_FIN, V_ORA_S3_INI, V_ORA_S3_FIN, V_ORA_S4_INI, V_ORA_S4_FIN, V_ORA_S5_INI, V_ORA_S5_FIN, V_ORA_S6_INI, V_ORA_S6_FIN, V_ORA_S7_INI, V_ORA_S7_FIN;
		EXIT WHEN CURSOR_CLASIFICACION_FE_EGR%NOTFOUND;
		UPDATE	FECXP_REP_PPTO_COM_CTA_ERP
		SET		CLA_FE_ID = V_CLA_FE_ID
		WHERE	(ORACLE_SEGMENTO1 >= NVL (V_ORA_S1_INI, '0'))
		AND		(ORACLE_SEGMENTO1 <= NVL (V_ORA_S1_FIN, 'z'))
		AND		(ORACLE_SEGMENTO2 >= NVL (V_ORA_S2_INI, '0'))
		AND		(ORACLE_SEGMENTO2 <= NVL (V_ORA_S2_FIN, 'z'))
		AND		(ORACLE_SEGMENTO3 >= NVL (V_ORA_S3_INI, '0'))
		AND		(ORACLE_SEGMENTO3 <= NVL (V_ORA_S3_FIN, 'z'))
		AND		(ORACLE_SEGMENTO4 >= NVL (V_ORA_S4_INI, '0'))
		AND		(ORACLE_SEGMENTO4 <= NVL (V_ORA_S4_FIN, 'z'))
		AND		(ORACLE_SEGMENTO5 >= NVL (V_ORA_S5_INI, '0'))
		AND		(ORACLE_SEGMENTO5 <= NVL (V_ORA_S5_FIN, 'z'))
		AND		(ORACLE_SEGMENTO6 >= NVL (V_ORA_S6_INI, '0'))
		AND		(ORACLE_SEGMENTO6 <= NVL (V_ORA_S6_FIN, 'z'))
		AND		(ORACLE_SEGMENTO7 >= NVL (V_ORA_S7_INI, '0'))
		AND		(ORACLE_SEGMENTO7 <= NVL (V_ORA_S7_FIN, 'z'))
		AND		NVL(V_TIPO_OPERACION_INI, 0) = 0
		AND		NVL(V_TIPO_OPERACION_FIN, 0) = 0
		AND		NVL (V_ID_BANCO_INI, 0) = 0
		AND		NVL (V_ID_BANCO_FIN, 0) = 0
		AND		NVL (LPAD (V_ID_CHEQUERA_INI, 20, '0'), '00000000000000000000') = '00000000000000000000'
		AND		NVL (LPAD (V_ID_CHEQUERA_FIN, 20, '0'), '00000000000000000000') = '00000000000000000000'
		AND		E_CODIGO = NVL (V_E_CODIGO, E_CODIGO)
		AND		NVL (CLA_FE_ID, '|') = '|';
		COMMIT;
	END LOOP;
	CLOSE	CURSOR_CLASIFICACION_FE_EGR;
	DELETE	FECXP_DET_CONT_VERSION_FE
	WHERE	PROCESO = 'FECXP_LLENA_DET_CONT_ERP';
	INSERT	INTO FECXP_DET_CONT_VERSION_FE (
			PROCESO, VERSION_FE)
	VALUES (
		   'FECXP_LLENA_DET_CONT_ERP', V_VERSION_FE);
	COMMIT;
	--===============================================================================================--
	--== TERMINA PPTO ==--
EXCEPTION
	WHEN NO_DATA_FOUND THEN
	RAISE_APPLICATION_ERROR(-20000,'NO HAY DATOS NUEVOS.');
END FECXP_LLENA_DET_CONT_ERP;
