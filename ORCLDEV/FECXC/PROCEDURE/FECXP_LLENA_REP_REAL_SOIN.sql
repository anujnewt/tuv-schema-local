CREATE OR REPLACE EDITIONABLE PROCEDURE "FECXC"."FECXP_LLENA_REP_REAL_SOIN" 
(
V_PERIODO 	  		  IN INT,
V_MES			  	  IN INT
)IS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
/*DECLARE
--	V_PERIODO      INT:= TO_NUMBER(TO_CHAR(SYSDATE,'YYYY'));
--	V_MES 	       INT:= TO_NUMBER(TO_CHAR(SYSDATE,'MM'));*/
	V_ID_SESION    VARCHAR2(25):= TO_CHAR(SYSDATE,'YYYYMMDD');
	V_CLA_FE_ID    FECXP_POLITICAS_SOIN.CLA_FE_ID%TYPE;
	V_POLITICA_SOIN_ID FECXP_POLITICAS_SOIN.POLITICA_SOIN_ID%TYPE;
	V_PRIORIDAD    FECXP_POLITICAS_SOIN.PRIORIDAD%TYPE;
	V_CTAM01_INI   FECXP_POLITICAS_SOIN.CTAM01_INI%TYPE;
	V_CTAM01_FIN   FECXP_POLITICAS_SOIN.CTAM01_FIN%TYPE;
	V_CTAM02_INI   FECXP_POLITICAS_SOIN.CTAM02_INI%TYPE;
	V_CTAM02_FIN   FECXP_POLITICAS_SOIN.CTAM02_FIN%TYPE;
	V_CTAM03_INI   FECXP_POLITICAS_SOIN.CTAM03_INI%TYPE;
	V_CTAM03_FIN   FECXP_POLITICAS_SOIN.CTAM03_FIN%TYPE;
	V_TIPO_INI     FECXP_POLITICAS_SOIN.TIPO_INI%TYPE;
	V_TIPO_FIN     FECXP_POLITICAS_SOIN.TIPO_FIN%TYPE;
	V_DIVISION_INI FECXP_POLITICAS_SOIN.DIVISION_INI%TYPE;
	V_DIVISION_FIN FECXP_POLITICAS_SOIN.DIVISION_FIN%TYPE;
	V_RUBRO_INI	   FECXP_POLITICAS_SOIN.RUBRO_INI%TYPE;
	V_RUBRO_FIN    FECXP_POLITICAS_SOIN.RUBRO_FIN%TYPE;
	CURSOR CURSOR_CLASIFICACION_FE IS
	SELECT	 CLA_FE_ID, PRIORIDAD, POLITICA_SOIN_ID, CTAM01_INI, CTAM01_FIN, CTAM02_INI, CTAM02_FIN,
			 CTAM03_INI, CTAM03_FIN, TIPO_INI, TIPO_FIN, DIVISION_INI, DIVISION_FIN, RUBRO_INI, RUBRO_FIN
	FROM	 FECXP_POLITICAS_SOIN
	WHERE  	 ACTIVA_REGLA = 1
	ORDER BY PRIORIDAD ASC;
BEGIN
	DELETE FROM FECXP_REP_REAL_SOIN
	WHERE PERIODO = V_PERIODO
	  AND MES 	  = V_MES;
	-- SE ISERTAN LAS DISTINTAS CUENTAS Q HAN GENERADO FE  --
	INSERT	 INTO FECXP_CUENTAS_SOIN_CARATULA (
			     E_CODIGO, CTAM01, CTAM02, CTAM03)
	SELECT	DISTINCT E.E_CODIGO, CS.CTAM01, CS.CTAM02, CS.CTAM03
	FROM	FECXP_ENC_PAGOS_SOIN E,
			FECXP_DET_PAGOS_SOIN PS,
			FECXP_CAT_CUENTAS_SOIN CS
	WHERE	TO_NUMBER (TO_CHAR (E.FECHA_APLICACION, 'YYYY')) = V_PERIODO
    AND		TO_NUMBER (TO_CHAR (E.FECHA_APLICACION, 'MM')) = V_MES
	AND		E.SECUENCIA_PAGOS_SOIN = PS.SECUENCIA_PAGOS_SOIN
	AND		PS.E_CODIGO = CS.E_CODIGO
	AND		PS.CTAM01 	= CS.CTAM01
	AND		PS.CTAM02 	= CS.CTAM02
	AND		PS.CTAM03 	= CS.CTAM03;
	-- SE CLASIFICAN LAS CUENTAS --
	OPEN  CURSOR_CLASIFICACION_FE;
	LOOP
		FETCH CURSOR_CLASIFICACION_FE
		INTO  V_CLA_FE_ID, V_PRIORIDAD, V_POLITICA_SOIN_ID, V_CTAM01_INI, V_CTAM01_FIN, V_CTAM02_INI, V_CTAM02_FIN, V_CTAM03_INI, V_CTAM03_FIN, V_TIPO_INI, V_TIPO_FIN, V_DIVISION_INI, V_DIVISION_FIN, V_RUBRO_INI, V_RUBRO_FIN;
        EXIT WHEN CURSOR_CLASIFICACION_FE%NOTFOUND;
		UPDATE	FECXP_CUENTAS_SOIN_CARATULA
		SET		CLA_FE_ID = V_CLA_FE_ID
		WHERE	(CTAM01 >= NVL (V_CTAM01_INI, '0'))
		AND		(CTAM01 <= NVL (V_CTAM01_FIN, 'z'))
		AND		(CTAM02 >= NVL (V_CTAM02_INI, '0'))
		AND		(CTAM02 <= NVL (V_CTAM02_FIN, 'z'))
		AND		(CTAM03 >= NVL (V_CTAM03_INI, '0'))
		AND		(CTAM03 <= NVL (V_CTAM03_FIN, 'z'))
/*		AND		(TIPO >= NVL (V_TIPO_INI, '0'))
		AND		(TIPO <= NVL (V_TIPO_FIN, 'z'))
		AND		(DIVISION >= NVL (V_DIVISION_INI, 0))
		AND		(DIVISION <= NVL (V_DIVISION_FIN, 9999))
		AND		(RUBRO >= NVL (V_RUBRO_INI, 0))
		AND		(RUBRO <= NVL (V_RUBRO_FIN, 9999))*/
		AND		NVL (CLA_FE_ID, '|') = '|';
	END LOOP;
	CLOSE CURSOR_CLASIFICACION_FE;
INSERT INTO FECXP_REP_REAL_SOIN
            (COD_EMPRESA, DES_EMPRESA, CLA_ID_FE, CLA_FE_DES, RUBRO, ORDEN_ID, ID_SESION, PERIODO, MES, FECHA_APLICACION,
			MONEDA, TIPO_CAMBIO, IMPORTE_LINEA, CTAM01, CTAM02, CTAM03, CG13GR, CG13RU, CTATIP)
   SELECT   ES.E_CODIGO, E.DES_EMPRESA, C.CLA_FE_ID, CFE.CLA_FE_DES, CFE.CLA_ATRIBUTO2, CFE.CLA_ATRIBUTO1, V_ID_SESION, V_PERIODO, V_MES,
   			ES.FECHA_APLICACION, M.MON_ORACLE, M.TIPO_CAMBIO, (DE.IMPORTE_LINEA*CFE.CLA_ATRIBUTO3), C.CTAM01, C.CTAM02, C.CTAM03, C.DIVISION, C.RUBRO, C.TIPO
     FROM   FECXC_EMPRESAS E,
			FECXP_CLASIFICACION_FE CFE,
	 		FECXP_CUENTAS_SOIN_CARATULA C,
            FECXP_ENC_PAGOS_SOIN ES,
			FECXP_DET_PAGOS_SOIN DE,
			FECXP_MONEDAS M
      WHERE E.E_CODIGO = ES.E_CODIGO
	    AND CFE.CLA_FE_ID = C.CLA_FE_ID
	    AND ES.SECUENCIA_PAGOS_SOIN = DE.SECUENCIA_PAGOS_SOIN
	    AND	DE.CTAM01 = C.CTAM01
        AND DE.CTAM02 = C.CTAM02
        AND DE.CTAM03 = C.CTAM03
		AND M.MON_SET = ES.MONEDA
		AND M.MES = TO_NUMBER(TO_CHAR(ES.FECHA_APLICACION,'MM'));
COMMIT;
END;
