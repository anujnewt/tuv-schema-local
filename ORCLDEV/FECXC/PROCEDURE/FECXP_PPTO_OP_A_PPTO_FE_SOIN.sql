CREATE OR REPLACE EDITIONABLE PROCEDURE "FECXC"."FECXP_PPTO_OP_A_PPTO_FE_SOIN" (
	V_VERSION_FE IN INTEGER,
	V_USUARIO_ID IN VARCHAR2,
	V_COMENTARIO IN VARCHAR2
) IS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
	V_PERIODO_EXTRACCION INTEGER;
	V_VERSION_EXTRACCION INTEGER;
	V_E_CODIGO INTEGER;
BEGIN
        SELECT	PERIODO_ORIGEN, VERSION_ORIGEN
		INTO	V_PERIODO_EXTRACCION, V_VERSION_EXTRACCION
		FROM	FECXP_PPTO_OPERATIVO_SOIN_ENC
        WHERE   VERSION_FE = V_VERSION_FE
		GROUP BY PERIODO_ORIGEN, VERSION_ORIGEN;
        DELETE  FECXP_PPTO_CONVERSION_SOIN
        WHERE   VERSION_FE = V_VERSION_FE AND E_CODIGO = NVL (V_E_CODIGO, E_CODIGO);
        COMMIT;
        DELETE  FECXC.FECXP_PPTO_CONVERSION_SOIN_ENC
        WHERE   VERSION_FE = V_VERSION_FE;
        COMMIT;
        INSERT  INTO FECXP_PPTO_CONVERSION_SOIN (
                        E_CODIGO,SECUENCIA_PPTO_OPERATIVO_SOIN, PERIODO, MESCOD, ARSMAP, AEJMAP,
                        CNCMAP, CTACR1, CTACR2, MONEDA, TIPO_CAMBIO, IMPORTE_LINEA, PERIODO_EXTRACCION,
                        MES_EXTRACCION, PRESUPUESTO_ESTATUS, VERSION_FE)
        SELECT  E_CODIGO,SECUENCIA_PPTO_OPERATIVO_SOIN.NEXTVAL, PERIODO, MESCOD, ARSMAP, AEJMAP,
                        CNCMAP, CTACR1, CTACR2, MONEDA, TIPO_CAMBIO, IMPORTE_LINEA, PERIODO_EXTRACCION,
                        MES_EXTRACCION, 'EXTRAIDO', VERSION_FE
        FROM    FECXP_PPTO_OPERATIVO_SOIN
        WHERE   VERSION_FE = V_VERSION_FE AND E_CODIGO = NVL (V_E_CODIGO, E_CODIGO);
        COMMIT;
		INSERT	INTO FECXC.FECXP_PPTO_CONVERSION_SOIN_ENC (
				VERSION_FE, COMENTARIO, USUARIO_ID, FECHA_EXTRACCION, VERSION_REGLAS, FECHA_VERSION_REGLAS, PERIODO_ORIGEN, VERSION_ORIGEN, ESTATUS_ORIGEN, VERSION_FE_ORIGEN)
		SELECT	VERSION_FE, V_COMENTARIO, V_USUARIO_ID, SYSDATE, 0, TO_DATE ('19000101', 'YYYYMMDD'), PERIODO, 0, 0, 0
		FROM	FECXP_PPTO_CONVERSION_SOIN
		WHERE	VERSION_FE = V_VERSION_FE AND E_CODIGO = NVL (V_E_CODIGO, E_CODIGO)
		GROUP BY VERSION_FE, PERIODO;
		COMMIT;
        --ACTUALIZA PRESUPUESTO (DE OPERATIVO A "CONVERTIDO" )  .
        UPDATE  FECXP_PPTO_CONVERSION_SOIN PFE
        SET             IMPORTE_LINEA = 0,
                        PRESUPUESTO_ESTATUS = 'CONVERTIDO'
        WHERE   EXISTS (
						SELECT	1
						FROM	FECXP_REGLAS_CONVERSION_PPTO RC
						WHERE	(PFE.E_CODIGO >= RC.REG_SEGMENTO1_INI OR RC.REG_SEGMENTO1_INI IS NULL)
						AND		(PFE.E_CODIGO <= RC.REG_SEGMENTO1_FIN OR RC.REG_SEGMENTO1_FIN IS NULL)
						AND		(PFE.ARSMAP >= RC.REG_SEGMENTO2_INI OR RC.REG_SEGMENTO2_INI IS NULL)
						AND		(PFE.ARSMAP <= RC.REG_SEGMENTO2_FIN OR RC.REG_SEGMENTO2_FIN IS NULL)
						AND		(PFE.AEJMAP >= RC.REG_SEGMENTO3_INI OR RC.REG_SEGMENTO3_INI IS NULL)
						AND		(PFE.AEJMAP <= RC.REG_SEGMENTO3_FIN OR RC.REG_SEGMENTO3_FIN IS NULL)
						AND		(PFE.CNCMAP >= RC.REG_SEGMENTO4_INI OR RC.REG_SEGMENTO4_INI IS NULL)
						AND		(PFE.CNCMAP <= RC.REG_SEGMENTO4_FIN OR RC.REG_SEGMENTO4_FIN IS NULL)
						AND		(PFE.CTACR1 >= RC.REG_SEGMENTO5_INI OR RC.REG_SEGMENTO5_INI IS NULL)
						AND		(PFE.CTACR1 <= RC.REG_SEGMENTO5_FIN OR RC.REG_SEGMENTO5_FIN IS NULL)
						AND		(PFE.CTACR2 >= RC.REG_SEGMENTO6_INI OR RC.REG_SEGMENTO6_INI IS NULL)
						AND		(PFE.CTACR2 <= RC.REG_SEGMENTO6_FIN OR RC.REG_SEGMENTO6_FIN IS NULL)
						AND		(PFE.PERIODO = RC.PERIODO OR RC.PERIODO IS NULL)
						AND		(PFE.MESCOD >= RC.MES_INI OR RC.MES_INI IS NULL)
						AND		(PFE.MESCOD <= RC.MES_FIN OR RC.MES_FIN IS NULL)
						AND		RC.PLATAFORMA = 'SOIN'
						AND		RC.MES_ACUMULACION = 0)
        AND		VERSION_FE = V_VERSION_FE AND E_CODIGO = NVL (V_E_CODIGO, E_CODIGO);
        COMMIT;
        UPDATE  FECXP_PPTO_CONVERSION_SOIN PFE
        SET             IMPORTE_LINEA = (
											SELECT	SUM (PA.IMPORTE_LINEA)
											FROM	FECXP_PPTO_CONVERSION_SOIN PA
											WHERE	PA.E_CODIGO = PFE.E_CODIGO
											AND		PA.ARSMAP = PFE.ARSMAP
											AND		PA.AEJMAP = PFE.AEJMAP
											AND		PA.CNCMAP = PFE.CNCMAP
											AND		PA.CTACR1 = PFE.CTACR1
											AND		PA.CTACR2 = PFE.CTACR2
											AND		PA.MONEDA = PFE.MONEDA
											AND		PA.VERSION_FE = PFE.VERSION_FE
											GROUP BY PFE.E_CODIGO, PFE.ARSMAP, PFE.AEJMAP, PFE.CNCMAP, PFE.CTACR1, PFE.CTACR2, PFE.MONEDA, PFE.PERIODO_EXTRACCION, PFE.MES_EXTRACCION
									  	),
                        PRESUPUESTO_ESTATUS = 'CONVERTIDO'
        WHERE   EXISTS (
						SELECT	1
						FROM	FECXP_REGLAS_CONVERSION_PPTO RC
						WHERE	(PFE.E_CODIGO >= RC.REG_SEGMENTO1_INI OR RC.REG_SEGMENTO1_INI IS NULL)
						AND		(PFE.E_CODIGO <= RC.REG_SEGMENTO1_FIN OR RC.REG_SEGMENTO1_FIN IS NULL)
						AND		(PFE.ARSMAP >= RC.REG_SEGMENTO2_INI OR RC.REG_SEGMENTO2_INI IS NULL)
						AND		(PFE.ARSMAP <= RC.REG_SEGMENTO2_FIN OR RC.REG_SEGMENTO2_FIN IS NULL)
						AND		(PFE.AEJMAP >= RC.REG_SEGMENTO3_INI OR RC.REG_SEGMENTO3_INI IS NULL)
						AND		(PFE.AEJMAP <= RC.REG_SEGMENTO3_FIN OR RC.REG_SEGMENTO3_FIN IS NULL)
						AND		(PFE.CNCMAP >= RC.REG_SEGMENTO4_INI OR RC.REG_SEGMENTO4_INI IS NULL)
						AND		(PFE.CNCMAP <= RC.REG_SEGMENTO4_FIN OR RC.REG_SEGMENTO4_FIN IS NULL)
						AND		(PFE.CTACR1 >= RC.REG_SEGMENTO5_INI OR RC.REG_SEGMENTO5_INI IS NULL)
						AND		(PFE.CTACR1 <= RC.REG_SEGMENTO5_FIN OR RC.REG_SEGMENTO5_FIN IS NULL)
						AND		(PFE.CTACR2 >= RC.REG_SEGMENTO6_INI OR RC.REG_SEGMENTO6_INI IS NULL)
						AND		(PFE.CTACR2 <= RC.REG_SEGMENTO6_FIN OR RC.REG_SEGMENTO6_FIN IS NULL)
						AND		(PFE.PERIODO = RC.PERIODO OR RC.PERIODO IS NULL)
						AND		(PFE.MESCOD >= RC.MES_INI OR RC.MES_INI IS NULL)
						AND		(PFE.MESCOD <= RC.MES_FIN OR RC.MES_FIN IS NULL)
						AND		RC.PLATAFORMA = 'SOIN'
						AND		RC.MES_ACUMULACION = PFE.MESCOD)
        AND		VERSION_FE = V_VERSION_FE AND E_CODIGO = NVL (V_E_CODIGO, E_CODIGO);
        COMMIT;
        UPDATE  FECXP_PPTO_CONVERSION_SOIN PFE
        SET             IMPORTE_LINEA = 0,
                        PRESUPUESTO_ESTATUS = 'CONVERTIDO'
        WHERE   EXISTS (
						SELECT	1
						FROM	FECXP_REGLAS_CONVERSION_PPTO RC
						WHERE	(PFE.E_CODIGO >= RC.REG_SEGMENTO1_INI OR RC.REG_SEGMENTO1_INI IS NULL)
						AND		(PFE.E_CODIGO <= RC.REG_SEGMENTO1_FIN OR RC.REG_SEGMENTO1_FIN IS NULL)
						AND		(PFE.ARSMAP >= RC.REG_SEGMENTO2_INI OR RC.REG_SEGMENTO2_INI IS NULL)
						AND		(PFE.ARSMAP <= RC.REG_SEGMENTO2_FIN OR RC.REG_SEGMENTO2_FIN IS NULL)
						AND		(PFE.AEJMAP >= RC.REG_SEGMENTO3_INI OR RC.REG_SEGMENTO3_INI IS NULL)
						AND		(PFE.AEJMAP <= RC.REG_SEGMENTO3_FIN OR RC.REG_SEGMENTO3_FIN IS NULL)
						AND		(PFE.CNCMAP >= RC.REG_SEGMENTO4_INI OR RC.REG_SEGMENTO4_INI IS NULL)
						AND		(PFE.CNCMAP <= RC.REG_SEGMENTO4_FIN OR RC.REG_SEGMENTO4_FIN IS NULL)
						AND		(PFE.CTACR1 >= RC.REG_SEGMENTO5_INI OR RC.REG_SEGMENTO5_INI IS NULL)
						AND		(PFE.CTACR1 <= RC.REG_SEGMENTO5_FIN OR RC.REG_SEGMENTO5_FIN IS NULL)
						AND		(PFE.CTACR2 >= RC.REG_SEGMENTO6_INI OR RC.REG_SEGMENTO6_INI IS NULL)
						AND		(PFE.CTACR2 <= RC.REG_SEGMENTO6_FIN OR RC.REG_SEGMENTO6_FIN IS NULL)
						AND		(PFE.PERIODO = RC.PERIODO OR RC.PERIODO IS NULL)
						AND		(PFE.MESCOD >= RC.MES_INI OR RC.MES_INI IS NULL)
						AND		(PFE.MESCOD <= RC.MES_FIN OR RC.MES_FIN IS NULL)
						AND		RC.PLATAFORMA = 'SOIN'
						AND		RC.MES_ACUMULACION <> PFE.MESCOD)
        AND		VERSION_FE = V_VERSION_FE AND E_CODIGO = NVL (V_E_CODIGO, E_CODIGO);
        COMMIT;
		INSERT	INTO FECXP_PPTO_BITACORA_PROCESOS (
				SEC_EXT_BITACORA, PROCESO_ID, FECHA_EXT_ULT_EJECUCION, ESTATUS_EXT_ULT_EJECUCION, PERIODO_PPTO_ULT_EJECUCION, VERSION_PPTO_ULT_EJECUCION, ESTATUS_PPTO_ULT_EJECUCION, VERSION_PPTO_GENERADO)
		VALUES	(SEC_EXT_BITACORA.NEXTVAL, 2,  SYSDATE, 'CONVERSION EXITOSA', V_PERIODO_EXTRACCION, V_VERSION_EXTRACCION, 'V', V_VERSION_FE);
        COMMIT;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20000,'No hay datos nuevos.');
END FECXP_PPTO_OP_A_PPTO_FE_SOIN;
