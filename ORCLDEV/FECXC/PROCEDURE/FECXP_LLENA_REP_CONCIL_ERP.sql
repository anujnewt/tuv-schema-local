	   AND T.ORACLE_SEGMENTO1 = RR.ORACLE_SEGMENTO1
       AND T.ORACLE_SEGMENTO2 = RR.ORACLE_SEGMENTO2
	   AND T.ORACLE_SEGMENTO3 = RR.ORACLE_SEGMENTO3
