		CASE WHEN MONEDA = 'MXP' THEN PO.PSS_01
			 WHEN MONEDA = 'USD' THEN PO.USD_01
			 WHEN MONEDA = 'EUR' THEN PO.EUR_01 END AS TIPO_CAMBIO,
		TO_DATE(PO.PERIODO_PPTO||'-'||01,'YYYY-MM') AS FECHA,
