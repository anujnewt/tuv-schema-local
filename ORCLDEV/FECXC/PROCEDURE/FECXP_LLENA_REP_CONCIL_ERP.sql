	   T.ORACLE_SEGMENTO1_DES, T.ORACLE_SEGMENTO2_DES, T.ORACLE_SEGMENTO3_DES, T.ORACLE_SEGMENTO4_DES, T.ORACLE_SEGMENTO5_DES,
