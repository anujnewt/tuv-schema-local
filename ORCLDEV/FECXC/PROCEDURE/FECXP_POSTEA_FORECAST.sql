	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_001.xml', ' </Encabezado>', V_SESION);
