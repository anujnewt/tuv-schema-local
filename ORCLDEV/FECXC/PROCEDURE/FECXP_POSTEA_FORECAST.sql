	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_001.xml', '	<mes>', V_SESION);
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) SELECT	SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_001.xml', XML_STRING, V_SESION
	FROM	(
			SELECT	'		<mes' || TO_CHAR (C.MES) || '>' || TO_CHAR (TO_DATE (C.MES, 'MM'), 'MON', 'NLS_DATE_LANGUAGE=SPANISH') || '</mes' || TO_CHAR (C.MES) || '>' XML_STRING
			FROM	FECXP_MONEDAS M,
					FECXP_REAL_CARATULA C,
					FECXC_EMP_X_SEGMENTO A
			WHERE	C.PERIODO = TO_NUMBER(TO_CHAR(SYSDATE,'YYYY'))
			AND		A.ID_SEGMENTO = 23
			AND		C.E_CODIGO = A.E_CODIGO
			AND		M.MON_ORACLE = C.MONEDA
			AND		M.PERIODO = C.PERIODO
			AND		M.MES = C.MES
