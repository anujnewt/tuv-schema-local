(
	V_COM_MES1 IN VARCHAR2,
	V_COM_MES2 IN VARCHAR2,
	V_COM_MES3 IN VARCHAR2,
	V_COM_MES4 IN VARCHAR2,
	V_COM_MES5 IN VARCHAR2,
	V_COM_MES6 IN VARCHAR2,
	V_COM_MES7 IN VARCHAR2,
	V_COM_MES8 IN VARCHAR2,
	V_COM_MES9 IN VARCHAR2,
	V_COM_MES10 IN VARCHAR2,
	V_COM_MES11 IN VARCHAR2,
	V_COM_MES12 IN VARCHAR2,
	V_COM_FIJO1 IN VARCHAR2,
	V_COM_FIJO2 IN VARCHAR2
)
IS
-- PGV moved types start

