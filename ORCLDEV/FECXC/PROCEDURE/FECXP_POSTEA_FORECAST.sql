	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_001.xml', '		<mes8>' || V_COM_MES8 || '</mes8>', V_SESION);
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_001.xml', '		<mes9>' || V_COM_MES9 || '</mes9>', V_SESION);
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_001.xml', '		<mes10>' || V_COM_MES10 || '</mes10>', V_SESION);
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_001.xml', '		<mes11>' || V_COM_MES11 || '</mes11>', V_SESION);
	INSERT	INTO FECXP_POSTEO (ORDEN, XML_DOC, XML_STRING, SESION) VALUES (SEC_FECXP_POSTEO.NEXTVAL, 'CE_FE_001.xml', '		<mes12>' || V_COM_MES12 || '</mes12>', V_SESION);
