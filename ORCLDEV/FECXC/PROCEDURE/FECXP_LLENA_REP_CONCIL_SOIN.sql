CREATE OR REPLACE EDITIONABLE PROCEDURE "FECXC"."FECXP_LLENA_REP_CONCIL_SOIN" 
(
V_PERIODO 	  		  IN INT,
V_MES			  	  IN INT
)IS
-- PGV moved types start

-- PGV moved types end

