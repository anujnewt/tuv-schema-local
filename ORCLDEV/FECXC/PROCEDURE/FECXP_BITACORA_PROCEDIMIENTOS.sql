CREATE OR REPLACE EDITIONABLE PROCEDURE "FECXC"."FECXP_BITACORA_PROCEDIMIENTOS" 
(
	P_USUARIO_ID  	 IN VARCHAR2,
	P_PROCESO_NUMERO IN INTEGER,
	P_ACCION  		 IN VARCHAR2
)
IS
-- PGV moved types start

-- PGV moved types end

-- PGV moved types start
-- PGV moved types end
	V_VERSION_PERP		VARCHAR2(100);
	V_VERSION_PSOIN		VARCHAR2(100);
	V_VERSION_ORDEN		VARCHAR2(100);
	V_CATALOGO_PERP		VARCHAR2(100) := 'FECXP_POLITICAS_ERP';
	V_CATALOGO_PSOIN	VARCHAR2(100) := 'FECXP_POLITICAS_SOIN';
	V_CATALOGO_ORDEN	VARCHAR2(100) := 'FECXP_CLASIFICACION_FE';
	V_PROCESO_NOMBRE 	VARCHAR2(100);
	V_DUMMY				VARCHAR2(100);
BEGIN
	V_PROCESO_NOMBRE :=
	CASE P_PROCESO_NUMERO
		 WHEN 1 THEN 'FECXP_LLENA_CARATULA_REAL'
		 WHEN 2 THEN 'FECXP_LLENA_CARATULA_FORESCAST'
		 WHEN 3 THEN 'FECXP_LLENA_CARATULA_PPTO'
		 WHEN 4 THEN 'FECXP_LLENA_DET_CONT_ERP'
		 WHEN 5 THEN 'FECXP_LLENA_DET_CONT_SOIN'
		 WHEN 6 THEN 'FECXP_LLENA_CARATULA_REALD/FECXP_LLENA_CARATULA_PPTO'
		 WHEN 7 THEN 'FECXP_POSTEA_COMPARATIVO'
		 WHEN 8 THEN 'FECXP_POSTEA_FORECAST'
		 WHEN 9 THEN 'FECXP_POSTEA_COMPARATIVO_D'
		 ELSE 'OTRO PROCESO'
	 END;
	IF P_ACCION = 'INICIO' THEN
	   SELECT SEC_EJECUCION_PROCESO.NEXTVAL INTO V_DUMMY FROM DUAL;
	END IF;
    SELECT DISTINCT VERSION_ID INTO V_VERSION_PERP FROM FECXP_POLITICAS_ERP;
    SELECT DISTINCT VERSION_ID INTO V_VERSION_PSOIN FROM FECXP_POLITICAS_SOIN;
	SELECT DISTINCT VERSION_ID INTO V_VERSION_ORDEN FROM FECXP_CLASIFICACION_FE;
	IF P_PROCESO_NUMERO >= 7 THEN
	   V_VERSION_PERP  := '0';
	   V_VERSION_PSOIN := '0';
	   V_VERSION_ORDEN := '0';
	   V_CATALOGO_PERP := 'N/A';
	   V_CATALOGO_PSOIN := 'N/A';
	   V_CATALOGO_ORDEN := 'N/A';
	END IF;
	INSERT INTO FECXP_B_EJECUCION_PROCESO(ID_PROCESO, PROCESO_NOMBRE,   CATALOGO_NOMBRE,	 VERSION_ID,   ACCION,   USUARIO_ID, FECHA_CREACION)
	SELECT SEC_EJECUCION_PROCESO.CURRVAL, 			V_PROCESO_NOMBRE, V_CATALOGO_PERP,   V_VERSION_PERP, P_ACCION, P_USUARIO_ID, SYSDATE
	FROM DUAL;
	IF P_PROCESO_NUMERO < 7 THEN
		INSERT INTO FECXP_B_EJECUCION_PROCESO(ID_PROCESO, PROCESO_NOMBRE,   CATALOGO_NOMBRE,	 VERSION_ID,   ACCION,   USUARIO_ID, FECHA_CREACION)
		SELECT SEC_EJECUCION_PROCESO.CURRVAL, 			V_PROCESO_NOMBRE, V_CATALOGO_PSOIN,   V_VERSION_PSOIN, P_ACCION, P_USUARIO_ID, SYSDATE
		FROM DUAL;
		INSERT INTO FECXP_B_EJECUCION_PROCESO(ID_PROCESO, PROCESO_NOMBRE,   CATALOGO_NOMBRE,	 VERSION_ID,   ACCION,   USUARIO_ID, FECHA_CREACION)
		SELECT SEC_EJECUCION_PROCESO.CURRVAL, 			V_PROCESO_NOMBRE, V_CATALOGO_ORDEN,   V_VERSION_ORDEN, P_ACCION, P_USUARIO_ID, SYSDATE
		FROM DUAL;
	END IF;
	COMMIT;
END FECXP_BITACORA_PROCEDIMIENTOS;
