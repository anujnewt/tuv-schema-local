CREATE OR REPLACE FUNCTION trigger_fct_fecxp_empresas_noset_det() RETURNS trigger AS $BODY$
DECLARE
BEGIN
UPDATE FECXC.FECXP_PPTO_CARATULA_IMPNS
SET E_CODIGO=NEW.ID_EMP
WHERE E_CODIGO  = NEW.ID_EMP_OLD;
UPDATE FECXC.FECXP_REAL_CARATULA_IMPNS
SET E_CODIGO=NEW.ID_EMP
WHERE E_CODIGO  = OLD.ID_EMP;
UPDATE FECXC.FECXP_EMP_X_SEGMENTO_NO_SET
SET E_CODIGO=NEW.ID_EMP
WHERE E_CODIGO  = NEW.ID_EMP_OLD;
RETURN NEW;
END
$BODY$
 LANGUAGE 'plpgsql';
