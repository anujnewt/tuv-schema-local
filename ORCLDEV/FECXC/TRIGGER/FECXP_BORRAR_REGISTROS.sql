CREATE OR REPLACE EDITIONABLE TRIGGER "FECXC"."FECXP_BORRAR_REGISTROS" BEFORE
DELETE ON FECXC.FECXP_IMP_DAT_HIST
FOR EACH ROW
BEGIN
IF :OLD.TIPO_IMPORTACION = 'R' THEN
    DELETE FECXC.FECXP_REAL_CARATULA_IMPNS A
    WHERE A.ID_LINEA                    =:OLD.ROWID;
END IF;
IF :OLD.TIPO_IMPORTACION = 'P' THEN
    DELETE FECXC.FECXP_PPTO_CARATULA_IMPNS B
    WHERE B.ID_LINEA      =:OLD.ROWID;
END IF;
END;

/;
ALTER TRIGGER "FECXC"."FECXP_BORRAR_REGISTROS" ENABLE;

/
ALTER TRIGGER "FECXC"."FECXP_BORRAR_REGISTROS" ENABLE;
