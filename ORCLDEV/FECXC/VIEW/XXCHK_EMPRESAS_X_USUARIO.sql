CREATE OR REPLACE FORCE EDITIONABLE VIEW "FECXC"."XXCHK_EMPRESAS_X_USUARIO" ("ID_ROL", "E_CODIGO", "CODUSUARIO") AS 
  select DISTINCT R.ID_ROL,RE.E_CODIGO,CODUSUARIO
		FROM    XXCHK_ROLES R,
			 	XXCHK_ROLES_XEMPRESA RE,
			 	XXCHK_ROLES_X_USUARIO RU
		WHERE R.ID_ROL = RE.ID_ROL
		AND	  R.ID_ROL = RU.ID_ROL
		AND	  RE.ID_ROL= RU.ID_ROL;
