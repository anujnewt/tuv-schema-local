CREATE OR REPLACE FORCE EDITIONABLE VIEW "FECXC"."FECXC_TPC_MULTIMONEDA_VW" ("FROM_CURRENCY", "TO_CURRENCY", "CONVERSION_DATE", "CONVERSION_RATE") AS 
  select FROM_CURRENCY, TO_CURRENCY, CONVERSION_DATE, CONVERSION_RATE
from gl.gl_daily_rates@erp_prod
WHERE STATUS_CODE LIKE 'O'
AND
CONVERSION_TYPE LIKE 'Corporate'
;
