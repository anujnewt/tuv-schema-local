CREATE OR REPLACE FORCE EDITIONABLE VIEW "FECXC"."FECXC_DIVXPERIODO_VW" ("ORDEN", "TIPO", "SUBTIPO", "SEGMENTO", "CANAL", "MES", "IMPORTE", "IMPORTENOM", "COD_VALOR", "DESSEGMENTO", "DESCANAL") AS 
  SELECT ORDEN,
  TIPO,
  SUBTIPO,
  SEGMENTO,
  CANAL,
  MES,
  IMPORTE,
  IMPORTENOM,
  B.COD_VALOR,
  B.DESC_VALOR "DESSEGMENTO",
  C.DESC_VALOR "DESCANAL"
FROM (
SELECT A.ORDEN,
  A.TIPO,
  A.SUBTIPO,
  A.SEGMENTO,
  A.CANAL,
  A.MES,
  A.IMPORTE,
  A.IMPORTENOM
FROM
  (SELECT 2        AS ORDEN,
    'A LA FECHA'   AS TIPO,
    'A?O ANTERIOR' AS SUBTIPO,
    SEGMENTO,
    CANAL,
    MES,
    SUM(A.COBRANZA_MES)     AS IMPORTE,
    SUM(A.COBRANZAREAL_MES) AS IMPORTENOM
  FROM FECXC_CANINTER_ALAFECH_COB_ANT A
  GROUP BY SEGMENTO,
    CANAL,
    MES
  UNION
  SELECT 2       AS ORDEN,
    'A LA FECHA' AS TIPO,
    'REAL'       AS SUBTIPO,
    SEGMENTO,
    CANAL,
    MES,
    SUM(A.COBRANZA_MES)     AS IMPORTE,
    SUM(A.COBRANZAREAL_MES) AS IMPORTENOM
  FROM FECXC_CANINTER_ALAFECH_COB_ACT A
  GROUP BY SEGMENTO,
    CANAL,
    MES
  UNION
  SELECT 2        AS ORDEN,
    'A LA FECHA'  AS TIPO,
    'PRESUPUESTO' AS SUBTIPO,
    SEGMENTO,
    CANAL,
    MES,
    SUM(A.PRESUP_MES)     AS IMPORTE,
    SUM(A.PRESUPREAL_MES) AS IMPORTENOM
  FROM FECXC_CANINTER_ALAFECHA_PRE A
  GROUP BY SEGMENTO,
    CANAL,
    MES
  UNION
  SELECT 2             AS ORDEN,
    'A LA FECHA'       AS TIPO,
    'VAR REAL VS PPTO' AS SUBTIPO,
    A.SEGMENTO,
    A.CANAL,
    A.MES,
    ( A.IMPORTE    - NVL(B.IMPORTE,0.00) )    AS IMPORTE,
    ( A.IMPORTENOM - NVL(B.IMPORTENOM,0.00) ) AS IMPORTENOM
  FROM
    (SELECT SEGMENTO,
      CANAL,
      MES,
      SUM(A.COBRANZA_MES)     AS IMPORTE,
      SUM(A.COBRANZAREAL_MES) AS IMPORTENOM
    FROM FECXC_CANINTER_ALAFECH_COB_ACT A
    GROUP BY SEGMENTO,
      CANAL,
      MES
    ) A,
    (SELECT SEGMENTO,
      CANAL,
      MES,
      SUM(A.PRESUP_MES)     AS IMPORTE,
      SUM(A.PRESUPREAL_MES) AS IMPORTENOM
    FROM FECXC_CANINTER_ALAFECHA_PRE A
    GROUP BY SEGMENTO,
      CANAL,
      MES
    ) B
  WHERE A.SEGMENTO = B.SEGMENTO (+)
  AND A.CANAL      = B.CANAL (+)
  UNION
  SELECT 2                           AS ORDEN,
    'A LA FECHA'                     AS TIPO,
    'VARIACI?N REAL VS A?O ANTERIOR' AS SUBTIPO,
    A.SEGMENTO,
    A.CANAL,
    A.MES,
    ( A.IMPORTE    - NVL(B.IMPORTE,0.00) )    AS IMPORTE,
    ( A.IMPORTENOM - NVL(B.IMPORTENOM,0.00) ) AS IMPORTENOM
  FROM
    (SELECT SEGMENTO,
      CANAL,
      MES,
      SUM(A.COBRANZA_MES)     AS IMPORTE,
      SUM(A.COBRANZAREAL_MES) AS IMPORTENOM
    FROM FECXC_CANINTER_ALAFECH_COB_ACT A
    GROUP BY SEGMENTO,
      CANAL,
      MES
    ) A,
    (SELECT SEGMENTO,
      CANAL,
      MES,
      SUM(A.COBRANZA_MES)     AS IMPORTE,
      SUM(A.COBRANZAREAL_MES) AS IMPORTENOM
    FROM FECXC_CANINTER_ALAFECH_COB_ANT A
    GROUP BY SEGMENTO,
      CANAL,
      MES
    ) B
  WHERE A.SEGMENTO = B.SEGMENTO (+)
  AND A.CANAL      = B.CANAL (+)
  ) A ) A,
  FECXC_DET_CATALOGOS B,
  FECXC_DET_CATALOGOS C
WHERE A.SEGMENTO = B.COD_SEC_LIN
AND B.TIPO_CAT   = 'SEGMENTO'
AND A.CANAL      = C.COD_SEC_LIN
AND ( C.TIPO_CAT = 'CANAL'
OR C.TIPO_CAT    = 'REGION'
OR C.TIPO_CAT    = 'DIVISION' );
