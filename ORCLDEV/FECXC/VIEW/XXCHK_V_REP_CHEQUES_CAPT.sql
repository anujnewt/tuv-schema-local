CREATE OR REPLACE FORCE EDITIONABLE VIEW "FECXC"."XXCHK_V_REP_CHEQUES_CAPT" ("ESTATUS_CHEQUE", "ID_ESTADO_CHEQUE", "BANCO", "CLIENTE", "REFERENCIA_CLIENTE", "NO_CHEQUE", "NO_CHEQUE_REEMPLAZO", "FECHA_ULTIMA_MODIFICACION", "FECHA_DE_CREACION", "IMPORTE", "MONEDA", "ANTIGUEDAD_ORIGEN", "ANTIGUEDAD_CAMBIO_EST", "SYSDATE_FECHA_COBRO", "CHEQUES_A_DEPOSITAR", "FECHA_EMISION", "FECHA_CAPUTRA", "FECHA_CAMBIO", "FECHA_COBRO", "ESRECHAZO") AS 
  SELECT DISTINCT
       CE.DESCRIPCION AS ESTATUS_CHEQUE,
       CE.ID_ESTADO_CHEQUE,
       CB.DESCRIPCION_BANCO AS BANCO,
       CC.DESC_CLIENTE AS CLIENTE,
       CC.REFERENCIA_CLIENTE,
       CC.NO_CHEQUE,
       CC.NO_CHEQUE_REEMPLAZO,
       TO_CHAR(CC.LAST_MODIFIED_DATE) AS FECHA_ULTIMA_MODIFICACION,
       TO_CHAR(CC.DATE_CREATED) AS FECHA_DE_CREACION,
       CC.IMPORTE,
       CC.MONEDA,
       TO_CHAR(TRUNC(SYSDATE-CC.DATE_CREATED,0)) AS ANTIGUEDAD_ORIGEN,
       TO_CHAR(TRUNC(SYSDATE-CC.LAST_MODIFIED_DATE,0)) AS ANTIGUEDAD_CAMBIO_EST,
       TO_CHAR(TRUNC(SYSDATE-CC.FECHA_COBRO,0)) AS SYSDATE_FECHA_COBRO,
       TO_CHAR(TRUNC(SYSDATE-CC.FECHA_EMISION,0)) AS CHEQUES_A_DEPOSITAR,
       CC.FECHA_EMISION,
       CC.DATE_CREATED as fecha_caputra,
       CC.LAST_MODIFIED_DATE as fecha_cambio,
       CC.FECHA_COBRO,
       'NORMAL' AS ESRECHAZO
FROM XXCHK_CAPTURA_CHEQUES CC,
     XXCHK_CATALOGO_BANCOS CB,
     XXCHK_CAT_EDOS CE
WHERE CC.ID_BANCO = CB.ID_BANCO
AND      CE.TIPO_OPERACION = 'RECHAZADO'
AND   CC.ID_ESTADO_CHEQUE =CE.ID_ESTADO_CHEQUE
UNION
SELECT DISTINCT
       CE.DESCRIPCION AS ESTATUS_CHEQUE,
       CE.ID_ESTADO_CHEQUE,
       CB.DESCRIPCION_BANCO AS BANCO,
       CC.DESC_CLIENTE AS CLIENTE,
       CC.REFERENCIA_CLIENTE,
       CC.NO_CHEQUE,
       CC.NO_CHEQUE_REEMPLAZO,
       TO_CHAR(CC.LAST_MODIFIED_DATE) AS FECHA_ULTIMA_MODIFICACION,
       TO_CHAR(CC.DATE_CREATED) AS FECHA_DE_CREACION,
       CC.IMPORTE,
       CC.MONEDA,
       TO_CHAR(TRUNC(SYSDATE-CC.DATE_CREATED,0)) AS ANTIGUEDAD_ORIGEN,
       TO_CHAR(TRUNC(SYSDATE-CC.LAST_MODIFIED_DATE,0)) AS ANTIGUEDAD_CAMBIO_EST,
       TO_CHAR(TRUNC(SYSDATE-CC.FECHA_COBRO,0)) AS SYSDATE_FECHA_COBRO,
       TO_CHAR(TRUNC(SYSDATE-CC.FECHA_EMISION,0)) AS CHEQUES_A_DEPOSITAR,
       CC.FECHA_EMISION,
       CC.DATE_CREATED as fecha_caputra,
       CC.LAST_MODIFIED_DATE as fecha_cambio,
       CC.FECHA_COBRO,
       'NORMAL' AS ESRECHAZO
FROM XXCHK_CAPTURA_CHEQUES CC,
     XXCHK_CATALOGO_BANCOS CB,
     XXCHK_CAT_EDOS CE
WHERE CC.ID_BANCO = CB.ID_BANCO
AND      CE.TIPO_OPERACION <> 'RECHAZADO'
AND   CC.ID_ESTADO_CHEQUE =CE.ID_ESTADO_CHEQUE;
