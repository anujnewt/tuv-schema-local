CREATE OR REPLACE FORCE EDITIONABLE VIEW "FECXC"."FECXC_EDITEXT_REP_VW" ("DIVISION_DESC", "CONCEPTO_DESC", "COBRANZA_DIA", "COBRANZA_MES", "PRESUP_MES", "VARIACION_MES", "PERC_MES", "COBRANZA_ALAFECHA", "PRESUP_ALAFECHA", "VARIACION_ALAFECHA", "PERC_ALAFECHA", "COBRANZA_ANTERIOR", "VARIACION_ANTERIOR", "PERC_ANTERIOR") AS 
  SELECT CASE WHEN DIVISION_DESC IS NULL AND CONCEPTO_DESC IS NULL THEN '~TOTAL EDITORIAL EXTRANJERO'
            ELSE DIVISION_DESC
       END AS DIVISION_DESC,
       CASE WHEN CONCEPTO_DESC IS NULL AND DIVISION_DESC IS NOT NULL THEN '~TOTAL ' || DIVISION_DESC
            ELSE CONCEPTO_DESC
       END AS CONCEPTO_DESC,
       COBRANZA_DIA, COBRANZA_MES, PRESUP_MES, VARIACION_MES, PERC_MES,
       COBRANZA_ALAFECHA, PRESUP_ALAFECHA, VARIACION_ALAFECHA, PERC_ALAFECHA,
       COBRANZA_ANTERIOR, VARIACION_ANTERIOR, PERC_ANTERIOR
FROM FECXC_EDITEXT_PASO_VW ;
