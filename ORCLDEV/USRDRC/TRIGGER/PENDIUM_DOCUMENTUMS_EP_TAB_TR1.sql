CREATE OR REPLACE NONEDITIONABLE TRIGGER "USRDRC"."PENDIUM_DOCUMENTUMS_EP_TAB_TR1" 
BEFORE INSERT ON USRDRC.PENDIUM_DOCUMENTUMS_EP_TAB 
FOR EACH ROW 
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_DOC_EP_PK IS NULL THEN
      SELECT PENDIUM_DOCUMENTUMS_EP_TAB_SE.NEXTVAL INTO :NEW.ID_DOC_EP_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;


/
ALTER TRIGGER "USRDRC"."PENDIUM_DOCUMENTUMS_EP_TAB_TR1" ENABLE;
