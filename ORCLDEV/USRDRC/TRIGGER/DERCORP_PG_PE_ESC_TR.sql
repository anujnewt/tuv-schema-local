CREATE OR REPLACE NONEDITIONABLE TRIGGER "USRDRC"."DERCORP_PG_PE_ESC_TR" 
BEFORE UPDATE OF VAL_C8 ON USRDRC.DERCORP_METATBL_TAB 
FOR EACH ROW 
   WHEN ((NEW.ID_FLEX_TBL  =17)OR(NEW.ID_FLEX_TBL =18)) DECLARE
BEGIN
    IF(:NEW.VAL_C8 <>'N/A') THEN
       UPDATE DERCORP_APODERADOS_TAB
       SET         DES_ESCRITURA = :NEW.VAL_C8
       WHERE  ID_EMPRESA       = :NEW.ID_EMPRESA
       AND       DES_ESCRITURA = :OLD.VAL_C8;
    END IF;

END;


/
ALTER TRIGGER "USRDRC"."DERCORP_PG_PE_ESC_TR" ENABLE;
