CREATE OR REPLACE NONEDITIONABLE TRIGGER "USRDRC"."PENDIUM_APODERADO_EP_TAB_TRG" 
BEFORE INSERT ON USRDRC.PENDIUM_APODERADO_EP_TAB 
FOR EACH ROW 
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_APOD_EP_PK IS NULL THEN
      SELECT PENDIUM_APODERADO_EP_SEQ.NEXTVAL INTO :NEW.ID_APOD_EP_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;


/
ALTER TRIGGER "USRDRC"."PENDIUM_APODERADO_EP_TAB_TRG" ENABLE;
