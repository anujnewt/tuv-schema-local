CREATE OR REPLACE NONEDITIONABLE TRIGGER "USRDRC"."DERCORP_ESC_CONS_TR" 
BEFORE UPDATE OF VAL_VALOR ON USRDRC.DERCORP_ADD_CAMPO_VALOR_TAB 
FOR EACH ROW 
   WHEN (NEW.ID_ADD_CAMPO  =551) DECLARE
BEGIN
    IF(:NEW.VAL_VALOR <>'N/A') THEN
       UPDATE DERCORP_APODERADOS_TAB
       SET         DES_ESCRITURA = :NEW.VAL_VALOR
       WHERE  ID_EMPRESA       = :NEW.ID_EMPRESA
       AND       DES_ESCRITURA = :OLD.VAL_VALOR;
    END IF;

END;


/
ALTER TRIGGER "USRDRC"."DERCORP_ESC_CONS_TR" ENABLE;
