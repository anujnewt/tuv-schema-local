CREATE OR REPLACE FUNCTION trigger_fct_log_flash() RETURNS trigger AS $body$
BEGIN
BEGIN
BEGIN
INSERT
INTO LOG_FLAS_TAB(
VALOR_ANTERIOR,
VALOR_ACTUAL,
CREATION_DATE,
NOM_DENOMINACION_ACTUAL,
NOM_DENOMINACION_ANTERIOR
)
VALUES (
OLD.val_valor,
NEW.val_valor,
statement_timestamp(),
(SELECT VAL_CAT_VAL
FROM DERCORP_ADD_CAMPO_CAT_VAL_TAB
WHERE id_catalogo = 1
AND id_catalogo_valor = NEW.val_valor),
(SELECT VAL_CAT_VAL
FROM DERCORP_ADD_CAMPO_CAT_VAL_TAB
WHERE id_catalogo = 1
AND id_catalogo_valor = OLD.val_valor)
);
EXCEPTION
WHEN OTHERS THEN
INSERT INTO LOG_FLAS_TAB(VALOR_ANTERIOR)
VALUES ('ERROR AL INSERTAR');
END;END;
RETURN NEW;
END
$body$
LANGUAGE 'plpgsql';
