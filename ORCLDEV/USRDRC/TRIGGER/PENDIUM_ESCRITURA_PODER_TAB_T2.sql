CREATE OR REPLACE NONEDITIONABLE TRIGGER "USRDRC"."PENDIUM_ESCRITURA_PODER_TAB_T2" 
BEFORE INSERT ON USRDRC.PENDIUM_ESCRITURA_PODER_TAB 
FOR EACH ROW 
BEGIN
  <<COLUMN_SEQUENCES>>
  BEGIN
    IF INSERTING AND :NEW.ID_EP_PK IS NULL THEN
      SELECT PENDIUM_ESCRITURA_PODER_TAB_S1.NEXTVAL INTO :NEW.ID_EP_PK FROM SYS.DUAL;
    END IF;
  END COLUMN_SEQUENCES;
END;


/
ALTER TRIGGER "USRDRC"."PENDIUM_ESCRITURA_PODER_TAB_T2" ENABLE;
