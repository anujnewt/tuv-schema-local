CREATE OR REPLACE FORCE NONEDITIONABLE VIEW "USRDRC"."DERCORP_ESCRITURAS_VW" ("ID_EMPRESA", "ESCRITURA") AS 
  SELECT ID_EMPRESA,
  VAL_C8 AS ESCRITURA
FROM DERCORP_METATBL_TAB M
WHERE 1         =1
AND ID_FLEX_TBL = 17
UNION ALL
SELECT ID_EMPRESA,
  VAL_C8 AS ESCRITURA
FROM DERCORP_METATBL_TAB M
WHERE 1         =1
AND ID_FLEX_TBL = 18
UNION ALL
SELECT ID_EMPRESA,
  VAL_VALOR AS ESCRITURA
FROM DERCORP_ADD_CAMPO_VALOR_TAB
WHERE ID_ADD_CAMPO = 551;
