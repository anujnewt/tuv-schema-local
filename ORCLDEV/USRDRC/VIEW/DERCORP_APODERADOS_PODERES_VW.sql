CREATE OR REPLACE FORCE NONEDITIONABLE VIEW "USRDRC"."DERCORP_APODERADOS_PODERES_VW" ("ID_EMPRESA", "NOM_EMPRESA", "DES_ESCRITURA", "NUM_TIPO_PODER", "TIPO_PODER", "DES_GRUPO", "ID_CATALOGO", "ID_CATALOGO_VALOR", "VAL_CAT_VAL", "DES_TIPO_BAJA", "DES_DOCUMENTO", "FEC_FECHA_BAJA") AS 
  SELECT
  EMP.ID_EMPRESA,
  EMP.NOM_EMPRESA,
  ESC.ESCRITURA AS DES_ESCRITURA,
  APOD.NUM_TIPO_PODER,
  CAT_TIPO.VAL_CAT_VAL TIPO_PODER,
  APOD.DES_GRUPO,
  APOD.ID_CATALOGO,
  APOD.ID_CATALOGO_VALOR,
  CAT_ELEM.VAL_CAT_VAL,
  APOD.DES_TIPO_BAJA,
  APOD.DES_DOCUMENTO,
  APOD.FEC_FECHA_BAJA
FROM
  DERCORP_EMPRESA_TAB EMP
  INNER JOIN DERCORP_ESCRITURAS_VW ESC ON ESC.ID_EMPRESA = EMP.ID_EMPRESA
  LEFT JOIN DERCORP_APODERADOS_TAB APOD ON APOD.ID_EMPRESA = EMP.ID_EMPRESA
                                        AND APOD.DES_ESCRITURA = ESC.ESCRITURA
                                        AND APOD.ID_CATALOGO <> 32
  INNER JOIN DERCORP_ADD_CAMPO_CAT_VAL_TAB CAT_TIPO ON CAT_TIPO.ID_CATALOGO_VALOR = APOD.NUM_TIPO_PODER
  INNER JOIN DERCORP_ADD_CAMPO_CAT_VAL_TAB CAT_ELEM ON CAT_ELEM.ID_CATALOGO_VALOR = APOD.ID_CATALOGO_VALOR;
