CREATE OR REPLACE FORCE NONEDITIONABLE VIEW "USRDRC"."DERCORP_REP_EST_DATOS_VW" ("ID_EMPRESA", "TIPO", "GRUPO", "ACCIONISTA", "RFC", "PAIS", "CAPITAL_FIJO", "CAPITAL_VARIABLE", "PORCENTAJE", "TOTAL") AS 
  SELECT "ID_EMPRESA","TIPO","GRUPO","ACCIONISTA","RFC","PAIS","CAPITAL_FIJO","CAPITAL_VARIABLE","PORCENTAJE","TOTAL" FROM (
SELECT
   MT.ID_EMPRESA,
  'Elemento' AS TIPO,
   MT.VAL_C8 AS GRUPO,
   (SELECT val_cat_val
    FROM dercorp_add_campo_cat_val_tab
    WHERE id_catalogo = 40
    AND   id_catalogo_valor = MT.VAL_C1) AS ACCIONISTA,
   NVL((SELECT atributo1
    FROM dercorp_add_campo_cat_val_tab
    WHERE id_catalogo = 40
    AND   id_catalogo_valor = MT.VAL_C1),'') AS RFC,
   NVL((SELECT atributo2
    FROM dercorp_add_campo_cat_val_tab
    WHERE id_catalogo = 40
    AND   id_catalogo_valor = MT.VAL_C1),'Mexico') AS PAIS,
   TO_NUMBER(MT.VAL_C3,'999999999999.999999') AS CAPITAL_FIJO,
   TO_NUMBER(MT.VAL_C4,'999999999999.999999') AS CAPITAL_VARIABLE,
   TO_NUMBER(MT.VAL_C5,'999999999999.999999') AS PORCENTAJE,
   TO_NUMBER(MT.VAL_C6,'999999999999.999999') AS TOTAL
FROM DERCORP_METATBL_TAB  MT
WHERE MT.ID_FLEX_TBL = 7
UNION ALL
SELECT
   MT.ID_EMPRESA,
  'TOTAL' AS TIPO,
  '' AS GRUPO,
  '' AS ACCIONISTA,
  '' AS RFC,
  '' AS PAIS,
   SUM(TO_NUMBER(MT.VAL_C3,'999999999999.999999')) AS CAPITAL_FIJO,
   SUM(TO_NUMBER(MT.VAL_C4,'999999999999.999999')) AS ACAPITAL_VARIABLE,
   SUM(TO_NUMBER(MT.VAL_C5,'999999999999.999999')) AS PORCENTAJE,
   SUM(TO_NUMBER(MT.VAL_C6,'999999999999.999999')) AS TOTAL
FROM DERCORP_METATBL_TAB  MT
WHERE MT.ID_FLEX_TBL = 7
GROUP BY MT.ID_EMPRESA, 'TOTAL', '') TOT;
