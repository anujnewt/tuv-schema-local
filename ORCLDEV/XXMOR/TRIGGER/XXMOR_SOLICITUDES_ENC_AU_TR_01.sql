      P_SOLICITUD.ID_SOLICITUD_HNA  := :NEW.ID_SOLICITUD_HNA;
      P_SOLICITUD.PROC_POR_LINEA    := :NEW.PROC_POR_LINEA;
      P_SOLICITUD.GARANTIZADO       := :NEW.GARANTIZADO;
      P_SOLICITUD.ADVID             := :NEW.ADVID;
      P_SOLICITUD.MCONTID           := :NEW.MCONTID;
      P_SOLICITUD.MCONTID_CUTIN     := :NEW.MCONTID_CUTIN;
      P_SOLICITUD.EMAIL             := :NEW.EMAIL;
      P_SOLICITUD.AGYESTNUM         := :NEW.AGYESTNUM;
      P_SOLICITUD.ACCTHDRID         := :NEW.ACCTHDRID;
      P_SOLICITUD.RTCRDDSCR         := :NEW.RTCRDDSCR;
      P_SOLICITUD.RTCRD             := :NEW.RTCRD;
      P_SOLICITUD.RTCRDDSCR_CUTIN   := :NEW.RTCRDDSCR_CUTIN;
      P_SOLICITUD.RTCRD_CUTIN       := :NEW.RTCRD_CUTIN;
      P_SOLICITUD.COMENTARIOS       := :NEW.COMENTARIOS;
      P_SOLICITUD.SECNUM            := :NEW.SECNUM;
      P_SOLICITUD.PLATAFORMA_CANAL  := :NEW.PLATAFORMA_CANAL;
      P_SOLICITUD.AGRUPADOR         := :NEW.AGRUPADOR;
      P_SOLICITUD.PRDID_DESC        := :NEW.PRDID_DESC;
      P_SOLICITUD.PRDID             := :NEW.PRDID;
      P_SOLICITUD.TOTAL_SPOTS       := :NEW.TOTAL_SPOTS;
      P_SOLICITUD.TOTAL_SIN_DESC    := :NEW.TOTAL_SIN_DESC;
      P_SOLICITUD.TOTAL_CON_DESC    := :NEW.TOTAL_CON_DESC;
      P_SOLICITUD.TIPO_FACTURACION  := :NEW.TIPO_FACTURACION;
      P_SOLICITUD.DESCUENTO         := :NEW.DESCUENTO;
      P_SOLICITUD.TARGET            := :NEW.TARGET;
      P_SOLICITUD.CREATED_DATE      := :NEW.CREATED_DATE;
      P_SOLICITUD.CREATED_BY        := :NEW.CREATED_BY;
      P_SOLICITUD.UPDATED_DATE      := :NEW.UPDATED_DATE;
      P_SOLICITUD.UPDATED_BY        := :NEW.UPDATED_BY;
      P_SOLICITUD.ORDEN_ESTATUS     := 10;

      UPDATE XXMOR_SOLICITUDES_DET_TAB
      SET LINEA_ESTATUS = 30
      WHERE ID_SOLICITUD = P_SOLICITUD.ID_SOLICITUD;  

    END IF;

END;
/
ALTER TRIGGER "XXMOR"."XXMOR_SOLICITUDES_ENC_AU_TR_01" ENABLE;
