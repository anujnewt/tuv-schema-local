CREATE OR REPLACE EDITIONABLE TRIGGER "XXMOR"."XXMOR_SOLICITUDES_ENC_AU_TR_01" 
AFTER UPDATE
OF ORDEN_ESTATUS
ON "XXMOR".XXMOR_SOLICITUDES_ENC_TAB 
REFERENCING NEW AS NEW OLD AS OLD
FOR EACH ROW
DECLARE

P_SOLICITUD xxmor_Funcional_pkg.Mor_Enc_Rec_Type;

BEGIN
    IF  :NEW.Id_seg_neg = 1 AND:NEW.ORDEN_ESTATUS = '30' AND:OLD.ORDEN_ESTATUS = '10' THEN     

      P_SOLICITUD.ID_SOLICITUD      := :NEW.ID_SOLICITUD;
      P_SOLICITUD.ID_REQUEST        := :NEW.ID_REQUEST;
      P_SOLICITUD.ID_SEG_NEG        := :NEW.ID_SEG_NEG;
