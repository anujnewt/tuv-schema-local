CREATE OR REPLACE FORCE EDITIONABLE VIEW "XXMOR"."XXLMK_ERRORES_ORD_LN_VW" ("ID_ERROR", "ID_ORDHDR", "NUM_LINEA", "DES_ERROR") AS 
  SELECT
    EL.ID_ERROR,
    L.ID_ORDHDR,
    L.NUM_LINEA,
    EL.DES_ERROR
FROM
    XXMOR.XXLMK_ERRORES_ORD_LNS_TAB EL
JOIN
    XXMOR.XXLMK_ORDLN_TAB L
ON
    EL.ID_LINEA = L.ID_LINEA
ORDER BY
    L.NUM_LINEA;
