CREATE OR REPLACE FORCE EDITIONABLE VIEW "XXMOR"."XXMOR_PANTALLA_INICIO1_VW" ("ID_NOTIFICACION", "DESC_NOTIFICACION", "ORDENES") AS 
  SELECT
        EST.ID_NOTIFICACION,
        EST.DESC_NOTIFICACION,
        (SELECT COUNT(*) FROM XXMOR_SOLICITUDES_ENC_TAB WHERE ORDEN_ESTATUS = EST.ID_NOTIFICACION AND ID_SEG_NEG = 1) ORDENES
    FROM
        XXMOR_ORDENES_ESTATUS_TAB EST
    WHERE
        (SELECT COUNT(*) FROM XXMOR_SOLICITUDES_ENC_TAB WHERE ORDEN_ESTATUS = EST.ID_NOTIFICACION AND ID_SEG_NEG = 1) != 0
    ORDER BY ID_NOTIFICACION ASC
 ;
