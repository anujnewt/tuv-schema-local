  SELECT
    SD.ID_SOLICITUD,
    SD.LINEA,
    SD.LINEA_HNA,
    (
        SELECT
            COUNT(1)
        FROM
            (
                SELECT DISTINCT
                    CRT.ID_SOLICITUD,
                    CRT.NUMLINEA_CONCOM
                FROM
                    XXMOR_CONCOM_RPTA_TAB CRT
                WHERE
                    CRT.ESTATUS_ORDUNI = '10'
                AND UPPER(ACCION_CONCOM) IN ('REPROCESO',
                                             'REENVIO')
                MINUS
                SELECT DISTINCT
                    CRT.ID_SOLICITUD,
                    CRT.NUMLINEA_CONCOM
                FROM
                    XXMOR_CONCOM_RPTA_TAB CRT
                WHERE
                    CRT.ESTATUS_ORDUNI = '10'
                AND UPPER(ACCION_CONCOM) IN ('RECHAZO',
                                             'RETENCION') ) RE
        WHERE
            RE.ID_SOLICITUD = SD.ID_SOLICITUD
        AND RE.NUMLINEA_CONCOM = SD.LINEA ) REPROCESOS,
    SD.STNID,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'STNID' ) ,0
    ) ERR_STNID,
    SD.FECHA_INICIO,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA,
    'FECHA_INICIO' ) ,0) ERR_FECHA_INICIO,
    SD.FECHA_FIN,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'FECHA_FIN'
    ) ,0) ERR_FECHA_FIN,
    SD.DURACION,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'DURACION' )
    ,0) ERR_DURACION,
    SD.BUYUNTID,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'BUYUNTID' )
    ,0) ERR_BUYUNTID,
    SD.HORA_INICIO,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA,
    'HORA_INICIO' ) ,0) ERR_HORA_INICIO,
    SD.HORA_FIN,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'HORA_FIN' )
    ,0) ERR_HORA_FIN,
    NVL(SD.SPOTS, XXMOR_FUNCIONAL_PKG.XXMOR_SOL_TOTALES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'SP_X_L' )
    ) SPOTS,
    XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'SPOTS' )
    ERR_SPOTS,
    SD.LUNES,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'LUNES' ) ,0
    ) ERR_LUNES,
    SD.MARTES,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'MARTES' ) ,
    0) ERR_MARTES,
    SD.MIERCOLES,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'MIERCOLES'
    ) ,0) ERR_MIERCOLES,
    SD.JUEVES,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'JUEVES' ) ,
    0) ERR_JUEVES,
    SD.VIERNES,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'VIERNES' )
    ,0) ERR_VIERNES,
    SD.SABADO,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'SABADO' ) ,
    0) ERR_SABADO,
    SD.DOMINGO,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'DOMINGO' )
    , 0) ERR_DOMINGO,
    NVL(SD.SPOTS_X_SEMANA, XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_SOL_TOTALES_FUN ( SD.ID_SOLICITUD,
    SD.LINEA, 'SS_X_L' ) ) SPOTS_X_SEMANA,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA,
    'SPOTS_X_SEMANA' ) ,0) ERR_SPOTS_X_SEMANA,
    SD.TIPO_SERVICIO,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA,
    'TIPO_SERVICIO' ) ,0) ERR_TIPO_SERVICIO,
    SD.USR_CHR,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'USR_CHR' )
    ,0) ERR_USR_CHR,
    SD.SPOT_CHR,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'SPT_CHR' )
    ,0) ERR_SPOT_CHR,
    SD.BN,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'BN' ) ,0)
    ERR_BN,
    SD.P,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'P' ) ,0)
    ERR_P,
    SD.MARCA,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'MARCA' ) ,0
    ) ERR_MARCA,
    SD.VERSION,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'VERSION' )
    ,0)                                              ERR_VERSION,
    TO_CHAR(SD.TARIFASP_SIN_DESC, '999999999999.99') TARIFASP_SIN_DESC,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA,
    'TARIFASP_SIN_DESC' ) ,0) ERR_TARIFASP_SIN_DESC,
    (TO_NUMBER(SD.TARIFASP_SIN_DESC) * 1 -- SE COMENTA PARA EVITAR ERROR CON DBLINK - XXMOR_FUNCIONAL_PKG.XXMOR_DESC_MCONTID_FUN(SE.ID_SOLICITUD)
    ) TARIFASP_CON_DESC,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA,
    'TARIFASP_CON_DESC' ) ,0) ERR_TARIFASP_CON_DESC,
    TO_CHAR(TO_NUMBER(SD.TARIFASP_SIN_DESC) * XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_SOL_TOTALES_FUN
    ( SD.ID_SOLICITUD, SD.LINEA, 'SP_X_L' ) ,'999999999999.99') TOT_LINEA_SIN_DESC,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA,
    'TOT_LINEA_SIN_DESC' ) ,0) ERR_TOT_LINEA_SIN_DESC,
    TO_CHAR(TO_NUMBER(SD.TARIFASP_SIN_DESC) * XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_SOL_TOTALES_FUN
    ( SD.ID_SOLICITUD, SD.LINEA, 'SP_X_L' ) * 1 -- SE COMENTA PARA EVITAR ERROR CON DBLINK - XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_DESC_MCONTID_FUN(SE.ID_SOLICITUD)
    ,'999999999999.99') TOT_LINEA_CON_DESC,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA,
    'TOT_LINEA_CON_DESC' ) ,0) ERR_TOT_LINEA_CON_DESC,
    SD.SOBRECARGO,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'SOBRECARGO'
    ) ,0) ERR_SOBRECARGO,
    SD.OBSERVACIONES,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA,
    'OBSERVACIONES' ) ,0) ERR_OBSERVACIONES,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_IDENT_ERRORES_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'RECHAZO' )
    ,0) ERR_RECHAZO,
    --R.ESTAT_ID_FORANEO ID_PRDG,
    (
        SELECT
            SER.ESTAT_ID_FORANEO
        FROM
            XXMOR_SOLICITUDES_EST_REP_TAB SER
        WHERE
            SER.ID_SOLICITUD = SE.ID_SOLICITUD
        AND SER.LINEA = SD.LINEA ) ID_PRDG,
    RO.ESTAT_ID_FORANEO            ID_ONAIR,
    --NVL (SD.LINEA_ESTATUS, 0)   AS LINEA_ESTATUS,
    NVL(XXMOR_FUNCIONAL_PKG.XXMOR_ORDEN_ESTATUS_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'ESTATUS_LINEA' )
    ,0)                     LINEA_ESTATUS,
    NVL(FZA.MATLOC_NULL, 0) MATLOC_NULL,
    NVL(FZA.MATLOC, 0)      MATLOC,
    NVL(XXMOR.XXMOR_FUNCIONAL_PKG.XXMOR_SOL_FECHAS_FUN ( SD.ID_SOLICITUD, SD.LINEA, 'F_U_T' ) ,0)
    FECHA_FINAL,
    NVL(
          (
          SELECT
              XCR.DESC_CONCOM||'/'||XCR.DETALLE_CONCOM
          FROM
              XXMOR_CONCOM_RPTA_TAB XCR
          WHERE
              UPPER(XCR.CAMPO_CONCOM) = 'OPENLOG'
          AND UPPER(XCR.ACCION_CONCOM) = 'AUTORIZACION'
          AND UPPER(XCR.POSICION_CONCOM) = 'LINEA'
          AND NVL(XCR.ESTATUS_ORDUNI, '10') = '10'
          AND XCR.ID_SOLICITUD = SD.ID_SOLICITUD
          AND XCR.NUMLINEA_CONCOM = SD.LINEA ),'0' ) AUT_OPENLOG,
    NVL(
          (
          SELECT
              XCR.DESC_CONCOM||'/'|| XCR.DETALLE_CONCOM
          FROM
              XXMOR_CONCOM_RPTA_TAB XCR
          WHERE
              UPPER(XCR.CAMPO_CONCOM) = 'TARIFA_MANUAL'
          AND UPPER(XCR.ACCION_CONCOM) = 'AUTORIZACION'
          AND UPPER(XCR.POSICION_CONCOM) = 'LINEA'
          AND NVL(XCR.ESTATUS_ORDUNI, '10') = '10'
          AND XCR.ID_SOLICITUD = SD.ID_SOLICITUD
          AND XCR.NUMLINEA_CONCOM = SD.LINEA ),'0' ) AUT_TM,
    NVL(
          (
          SELECT
              XCR.DESC_CONCOM||'/'||XCR.DETALLE_CONCOM
          FROM
              XXMOR_CONCOM_RPTA_TAB XCR
          WHERE
              UPPER(XCR.CAMPO_CONCOM) = 'SOBRECARGO'
          AND UPPER(XCR.ACCION_CONCOM) = 'AUTORIZACION'
          AND UPPER(XCR.POSICION_CONCOM) = 'LINEA'
          AND NVL(XCR.ESTATUS_ORDUNI, '10') = '10'
          AND XCR.ID_SOLICITUD = SD.ID_SOLICITUD
          AND XCR.NUMLINEA_CONCOM = SD.LINEA ),'0' ) AUT_SOBREGARGO,
    NVL(
          (
          SELECT
              XCR.DESC_CONCOM||'/'||XCR.DETALLE_CONCOM
          FROM
              XXMOR_CONCOM_RPTA_TAB XCR
          WHERE
              UPPER(XCR.CAMPO_CONCOM) = 'URGENTE'
          AND UPPER(XCR.ACCION_CONCOM) = 'AUTORIZACION'
          AND UPPER(XCR.POSICION_CONCOM) = 'LINEA'
          AND NVL(XCR.ESTATUS_ORDUNI, '10') = '10'
          AND XCR.ID_SOLICITUD = SD.ID_SOLICITUD
          AND XCR.NUMLINEA_CONCOM = SD.LINEA ),'0' ) AUT_URGENTE,
    SD.DES_PLATAFORMA,
    SE.MCONTID
FROM
    XXMOR_SOLICITUDES_DET_TAB SD,
    XXMOR_SOLICITUDES_ENC_TAB SE,
    XXMOR_SOLICITUDES_EST_REP_TAB R,
    XXMOR_SOLICITUDES_EST_REP_TAB RO,
    XXMOR_FZAS_VTAS_TAB FZA
WHERE
    SE.ID_SEG_NEG = 1
AND SD.ID_SOLICITUD = R.ID_SOLICITUD(+)
AND R.LINEA(+) = 0
AND R.ID_SIST(+) = 1
AND SD.ID_SOLICITUD = RO.ID_SOLICITUD(+)
AND RO.LINEA(+) = 0
AND RO.ID_SIST(+) = 2
AND SD.ID_SOLICITUD = SE.ID_SOLICITUD
AND SE.ID_FZA_VENTAS = FZA.ID_FZA_VENTAS
ORDER BY
    SD.LINEA;
