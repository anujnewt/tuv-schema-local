 SELECT LABCONF.cfdi2ComprobanteEmp_seq.NEXTVAL INTO :NEW.idComprobanteEmp FROM DUAL;
END;



/
ALTER TRIGGER "LABCONF"."CFDI2COMPROBANTEEMP_SEQ_TR" ENABLE;
