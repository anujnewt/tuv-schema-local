CREATE OR REPLACE EDITIONABLE TRIGGER "LABCONF"."CFDI2COMPROBANTEEMP_SEQ_TR" 
 BEFORE INSERT ON LABCONF.cfdi2ComprobanteEmp FOR EACH ROW
