CREATE OR REPLACE EDITIONABLE TRIGGER "LABCONF"."RECIBOS_GENERACION_SEQ_TR" 
 BEFORE INSERT ON LABCONF.RECIBOS_GENERACION FOR EACH ROW
    WHEN (
NEW.ID IS NULL
      ) BEGIN
 SELECT LABCONF.RECIBOS_GENERACION_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL;
END;



/
ALTER TRIGGER "LABCONF"."RECIBOS_GENERACION_SEQ_TR" ENABLE;
