CREATE OR REPLACE FUNCTION trigger_fct_tr_sipros_erp_enc() RETURNS trigger AS $body$
DECLARE
W_NUM_ERROR    	numeric(6);
W_MENSAJE      	varchar(100);
VAPE_KEYPOL     varchar(30);
VAPE_STATUS     varchar(1);
BEGIN
BEGIN
IF TG_OP = 'UPDATE' THEN
VAPE_KEYPOL:=NEW.APE_KEYPOL;
VAPE_STATUS:=NEW.APE_STATUS;
END IF;
-- ACTUALIZA EN LA TABLA TVLOFACE
UPDATE LABCONF.TVLOFACE
SET FEN_STATUS = VAPE_STATUS
WHERE FEN_KEYFAC = VAPE_KEYPOL;
EXCEPTION
WHEN OTHERS THEN
W_NUM_ERROR := SQLSTATE;
W_MENSAJE := oracle.SUBSTR(SQLERRM,1,100);END;
RETURN NEW;
END
$body$
LANGUAGE 'plpgsql';
