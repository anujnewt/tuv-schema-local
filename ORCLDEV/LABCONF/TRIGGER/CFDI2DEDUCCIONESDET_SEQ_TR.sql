CREATE OR REPLACE EDITIONABLE TRIGGER "LABCONF"."CFDI2DEDUCCIONESDET_SEQ_TR" 
 BEFORE INSERT ON LABCONF.cfdi2DeduccionesDetalle FOR EACH ROW
      WHEN (NEW.idDeduccion IS NULL) BEGIN
 SELECT LABCONF.cfdi2DeduccionesDetalle_seq.NEXTVAL INTO :NEW.idDeduccion FROM DUAL;
END;



/
ALTER TRIGGER "LABCONF"."CFDI2DEDUCCIONESDET_SEQ_TR" ENABLE;
