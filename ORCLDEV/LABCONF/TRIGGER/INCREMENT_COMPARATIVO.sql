CREATE OR REPLACE EDITIONABLE TRIGGER "LABCONF"."INCREMENT_COMPARATIVO" 
   BEFORE INSERT
     ON LABCONF.comparativo
     REFERENCING NEW AS NEW
     FOR EACH ROW
   BEGIN
     SELECT seq_comparativo.nextval INTO :NEW.ID_comp FROM dual;
   END;




/
ALTER TRIGGER "LABCONF"."INCREMENT_COMPARATIVO" ENABLE;
