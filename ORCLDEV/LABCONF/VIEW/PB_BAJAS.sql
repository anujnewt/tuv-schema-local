CREATE OR REPLACE FORCE EDITIONABLE VIEW "LABCONF"."PB_BAJAS" ("FECHA_CAPTURA", "KEYEMP", "NOMBRE", "PROCESO", "DESC_PROCESO", "AMBIENTE_ACTUAL", "FECHA_BAJA", "TIPO_BAJA", "DESC_TIPOBAJA", "KEYEMP_NUEVO", "PROCESO_NUEVO", "DESC_PROCESO_NUEVO", "AMBIENTE_NUEVO", "ESTATUS", "DESC_STATUS") AS 
  SELECT BAJ_FECCAP FECHA_CAPTURA,
          BAJ_KEYEMP KEYEMP,
          EMP_NOMEMP NOMBRE,
          EMP_KEYPRO PROCESO,
          PRO.PRO_DESPRO DESC_PROCESO,
          CASE WHEN SEPB.PAM_CVESEC IS NULL THEN 'TELEVISA' ELSE 'TELECOM' END AMBIENTE_ACTUAL,
          BAJ_FECBAJ FECHA_BAJA,
          BAJ_CVEBAJ TIPO_BAJA,
          BA.PAM_NOMPAR DESC_TIPOBAJA,
          BAJ_TRAEMP KEYEMP_NUEVO,
          BAJ_TRAPRO PROCESO_NUEVO,
          PROTRA.PRO_DESPRO DESC_PROCESO_NUEVO,
          CASE WHEN BAJ_TRAPRO IS NULL THEN '' WHEN SEPB2.PAM_CVESEC IS NULL THEN 'TELEVISA' ELSE 'TELECOM' END AMBIENTE_NUEVO,
          BAJ_STATUS ESTATUS,
          CASE
             WHEN BAJ_STATUS = '1' THEN 'PRE-BAJA'
             WHEN BAJ_STATUS = '2' THEN 'BAJA'
             WHEN BAJ_STATUS = '3' THEN 'CANCELACION PREBAJA'
             WHEN BAJ_STATUS = '4' THEN 'CANCELACION BAJA'
             ELSE 'NO EXISTE DESCRIPCION'
          END
             DESC_STATUS
     FROM LABCONF.SCCOBAJA
          INNER JOIN LABCONF.NMCOEMPL ON BAJ_KEYEMP = EMP_KEYEMP
          INNER JOIN LABCONF.NMLOPROC PRO ON EMP_KEYPRO = PRO.PRO_KEYPRO
          INNER JOIN LABCONF.GLCOPAMS BA
             ON BA.PAM_KEYPAR = 'BA' AND BA.PAM_CVESEC = BAJ_CVEBAJ
          LEFT JOIN LABCONF.NMLOPROC PROTRA ON PROTRA.PRO_KEYPRO = BAJ_TRAPRO
          LEFT JOIN LABCONF.GLCOPAMS SEPB
             ON SEPB.PAM_KEYPAR = 'SEPB' AND SEPB.PAM_CVESEC = EMP_KEYPRO
          LEFT JOIN LABCONF.GLCOPAMS SEPB2
             ON SEPB2.PAM_KEYPAR = 'SEPB' AND SEPB2.PAM_CVESEC = BAJ_TRAPRO;
