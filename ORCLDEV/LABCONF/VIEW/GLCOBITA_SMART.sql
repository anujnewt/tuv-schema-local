CREATE OR REPLACE FORCE EDITIONABLE VIEW "LABCONF"."GLCOBITA_SMART" ("BIT_KEYUSU", "BIT_LOGUSU", "BIT_IDEPCC", "BIT_FECMOV", "BIT_HORMOV", "BIT_TIPMOV", "BIT_KEY001", "BIT_KEY002", "BIT_KEY003", "BIT_VAL001", "BIT_VAL002", "BIT_VAL003", "BIT_DESMEN", "BIT_IDENIV") AS 
  SELECT BIT_KEYUSU,
          BIT_LOGUSU,
          BIT_IDEPCC,
          TO_DATE (TO_CHAR (BIT_FECMOV, 'DD/MM/YYYY') || ' ' || BIT_HORMOV,
                   'DD/MM/YYYY HH24:MI:SS')
             BIT_FECMOV,
          BIT_HORMOV,
          BIT_TIPMOV,
          BIT_KEY001,
          BIT_KEY002,
          BIT_KEY003,
          BIT_VAL001,
          BIT_VAL002,
          BIT_VAL003,
          BIT_DESMEN,
          BIT_IDENIV
     FROM LABCONF.GLCOBITA
    WHERE BIT_FECMOV IS NOT NULL;
