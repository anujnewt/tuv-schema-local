CREATE OR REPLACE EDITIONABLE TRIGGER "USRSIHO"."HOLODETLLA_TRG" 
BEFORE INSERT
ON USRSIHO.HOLODETLLA
REFERENCING NEW AS New OLD AS Old
FOR EACH ROW
BEGIN
-- For Toad:  Highlight column DET_SERIAL
  :new.DET_SERIAL := HOLODETLLA_SEQ.nextval;
END HOLODETLLA_TRG;


/
ALTER TRIGGER "USRSIHO"."HOLODETLLA_TRG" ENABLE;
