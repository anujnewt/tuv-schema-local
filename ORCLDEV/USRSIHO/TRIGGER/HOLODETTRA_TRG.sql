CREATE OR REPLACE EDITIONABLE TRIGGER "USRSIHO"."HOLODETTRA_TRG" 
BEFORE INSERT
ON USRSIHO.HOLODETTRA
REFERENCING NEW AS New OLD AS Old
FOR EACH ROW
BEGIN
-- For Toad:  Highlight column DET_SERIAL
  :new.DET_SERIAL := HOLODETTRA_SEQ.nextval;
END HOLODETTRA_TRG;


/
ALTER TRIGGER "USRSIHO"."HOLODETTRA_TRG" ENABLE;
