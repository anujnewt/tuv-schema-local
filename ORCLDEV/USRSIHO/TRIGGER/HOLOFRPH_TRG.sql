CREATE OR REPLACE EDITIONABLE TRIGGER "USRSIHO"."HOLOFRPH_TRG" 
BEFORE INSERT
ON USRSIHO.HOLOFRPH
REFERENCING NEW AS NEW OLD AS OLD
FOR EACH ROW
BEGIN
      IF( :new.FRP_KEYRPH IS NULL or :new.FRP_KEYRPH = 0 ) then
        SELECT HOLOFRPH_seq.nextval INTO :new.FRP_KEYRPH FROM dual;
      end if;
    END;


/
ALTER TRIGGER "USRSIHO"."HOLOFRPH_TRG" ENABLE;
