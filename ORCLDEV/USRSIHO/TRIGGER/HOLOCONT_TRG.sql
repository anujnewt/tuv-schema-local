CREATE OR REPLACE EDITIONABLE TRIGGER "USRSIHO"."HOLOCONT_TRG" 
BEFORE INSERT
ON USRSIHO.HOLOCONT
REFERENCING NEW AS New OLD AS Old
FOR EACH ROW
BEGIN
-- For Toad:  Highlight column CON_KEYPLZ
IF( :new.CON_KEYPLZ IS NULL or :new.CON_KEYPLZ = 0 ) then
  :new.CON_KEYPLZ := HOLOCONT_SEQ.nextval;
end if;
END HOLOCONT_TRG;


/
ALTER TRIGGER "USRSIHO"."HOLOCONT_TRG" ENABLE;
