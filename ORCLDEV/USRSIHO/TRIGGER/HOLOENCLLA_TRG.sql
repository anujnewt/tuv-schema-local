BEFORE INSERT
ON USRSIHO.HOLOENCLLA
REFERENCING NEW AS New OLD AS Old
FOR EACH ROW
BEGIN
-- For Toad:  Highlight column ENC_NUM_ID
  :new.ENC_NUM_ID := HOLOENCLLA_SEQ.nextval;
END HOLOENCLLA_TRG;


/
ALTER TRIGGER "USRSIHO"."HOLOENCLLA_TRG" ENABLE;
