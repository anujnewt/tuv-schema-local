CREATE OR REPLACE FUNCTION trigger_fct_fecxp_borrar_registros() RETURNS trigger AS $body$
BEGIN
/* DMAP CONVERTED STATEMENT START */
IF OLD.TIPO_IMPORTACION = 'R' THEN
DELETE FROM FECXC.FECXP_REAL_CARATULA_IMPNS A
WHERE A.ID_LINEA                    =MD5(CAST(OLD.ctid AS TEXT));/* DMAP CONVERTED STATEMENT END */
END IF;/* DMAP CONVERTED STATEMENT START */
IF OLD.TIPO_IMPORTACION = 'P' THEN
DELETE FROM FECXC.FECXP_PPTO_CARATULA_IMPNS B
WHERE B.ID_LINEA      =MD5(CAST(OLD.ctid AS TEXT));/* DMAP CONVERTED STATEMENT END */
END IF;
END;

$body$
LANGUAGE 'plpgsql';
